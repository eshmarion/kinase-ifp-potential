"""Слияние сгенерированных разделов markdown с разделами, дописанными руками.

Отчёт, который собирает код, почти никогда не остаётся целиком машинным: к посчитанным
числам дописывают разбор, и дальше файл принадлежит двоим. Запись целиком в такой
ситуации молча стирает чужую половину — так `scripts/calibrate_ifp.py` терял раздел 3
`docs/calibration.md`, разбор механизма расхождения по `HYD`, при каждом пересчёте
выборки. Здесь запись целиком заменена слиянием: сгенерированные разделы встают
на свои места, все прочие сохраняются дословно.

Второй потребитель известен заранее и требует того же
«новые числа рядом со старыми» для `docs/metrics.md`.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass

# Заголовок второго уровня: `## `, но не `### `. Разделы первого уровня не трогаем —
# в наших отчётах он один и служит названием файла.
_ЗАГОЛОВОК = re.compile(r"^##(?!#)\s+(?P<текст>.+)$")

# Номер раздела в начале заголовка: `## 2. Полная сверка…` → «2».
_НОМЕР = re.compile(r"^##(?!#)\s+(?P<номер>\d+(?:\.\d+)*)\.")

# Ограждённый блок кода. Строка `## …` внутри него заголовком не является:
# в `docs/calibration.md` таким блоком записан SMARTS-шаблон ProLIF.
_ЗАБОР = re.compile(r"^\s*(?:```|~~~)")


class MarkdownError(RuntimeError):
    """Документ или сгенерированный раздел устроены не так, как ожидает слияние."""


@dataclass(frozen=True)
class MarkdownSection:
    """Раздел второго уровня: чем он опознаётся, его заголовок и весь текст."""

    key: str
    heading: str
    lines: tuple[str, ...]


def _ключ(heading: str) -> str:
    """Номер раздела, а если номера нет — его заголовок без регистра и лишних пробелов.

    Ключом служит именно номер: заголовок раздела 1 в `docs/calibration.md` несёт код
    мишени («Дымовая сверка на мишени 6tgu») и меняется вместе с ключом `--target`.
    Сравнение по тексту заголовка положило бы в файл два первых раздела вместо одного.
    """
    номер = _НОМЕР.match(heading)
    if номер:
        return номер.group("номер")
    текст = _ЗАГОЛОВОК.match(heading)
    if текст is None:
        raise MarkdownError(f"строка не является заголовком раздела: {heading!r}")
    return " ".join(текст.group("текст").split()).lower()


def _обрезать(строки: Sequence[str]) -> list[str]:
    """Снимает хвостовые пустые строки.

    Без этого повторное слияние накапливало бы пустые строки, и «ничего не изменилось»
    перестало бы быть побайтовым: разделы склеиваются ровно одной пустой строкой.
    """
    итог = list(строки)
    while итог and not итог[-1].strip():
        итог.pop()
    return итог


def split_sections(text: str) -> tuple[list[str], list[MarkdownSection]]:
    """Делит документ на преамбулу до первого `## ` и разделы второго уровня.

    Возвращает строки преамбулы и разделы в порядке файла. Два раздела с одним ключом
    роняют вызов: дальше по ключу выбирается, какой заменить, и молчаливый выбор одного
    из двух означал бы потерю второго.
    """
    преамбула: list[str] = []
    разделы: list[MarkdownSection] = []
    текущий: list[str] | None = None
    в_заборе = False

    for строка in text.splitlines():
        if _ЗАБОР.match(строка):
            в_заборе = not в_заборе
        elif not в_заборе and _ЗАГОЛОВОК.match(строка):
            if текущий is not None:
                разделы.append(_в_раздел(текущий))
            текущий = [строка]
            continue
        if текущий is None:
            преамбула.append(строка)
        else:
            текущий.append(строка)

    if текущий is not None:
        разделы.append(_в_раздел(текущий))

    ключи = [р.key for р in разделы]
    повторы = sorted({к for к in ключи if ключи.count(к) > 1})
    if повторы:
        raise MarkdownError(f"в документе повторяется раздел: {', '.join(повторы)}")

    return _обрезать(преамбула), разделы


def _в_раздел(строки: Sequence[str]) -> MarkdownSection:
    """Собирает раздел из его строк: первая обязана быть заголовком `## `."""
    обрезанные = _обрезать(строки)
    if not обрезанные:
        raise MarkdownError("пустой раздел: нечего записывать")
    заголовок = обрезанные[0]
    if not _ЗАГОЛОВОК.match(заголовок):
        raise MarkdownError(
            f"раздел обязан начинаться заголовком '## ', а начинается с {заголовок!r}"
        )
    return MarkdownSection(key=_ключ(заголовок), heading=заголовок, lines=tuple(обрезанные))


def merge_sections(
    old: str | None,
    generated: Sequence[Sequence[str]],
    *,
    preamble: Sequence[str],
) -> str:
    """Возвращает документ, где сгенерированные разделы заменены, а прочие сохранены.

    `old` — прежний текст документа или `None`, если файла ещё нет. `generated` —
    разделы, посчитанные этим прогоном, каждый строками и с заголовком `## ` первой
    строкой. `preamble` — шапка документа; она используется **только при создании
    файла с нуля**.

    Преамбула существующего файла не трогается никогда. В `docs/calibration.md` она
    несёт строку «Посчитано ‹дата›», относящуюся к разделу 2, и прогон, пересчитавший
    разделы 1 и 4, не вправе переставить дату чужого измерения. Поэтому каждый
    генератор печатает свою дату внутри своего раздела.

    Разделы, которых в этом прогоне не было, остаются на прежних местах; разделов,
    которых в документе ещё нет, дописываются в конец в порядке поступления. Запись
    в файл — дело вызывающего: так функция проверяется без временных каталогов.
    """
    готовые = [_в_раздел(блок) for блок in generated]
    ключи = [р.key for р in готовые]
    повторы = sorted({к for к in ключи if ключи.count(к) > 1})
    if повторы:
        raise MarkdownError(f"один и тот же раздел сгенерирован дважды: {', '.join(повторы)}")

    if old is None or not old.strip():
        блоки: list[Sequence[str]] = [list(preamble), *(р.lines for р in готовые)]
    else:
        старая_преамбула, старые = split_sections(old)
        по_ключу = {р.key: р for р in готовые}
        блоки = [старая_преамбула]
        блоки += [по_ключу[р.key].lines if р.key in по_ключу else р.lines for р in старые]
        известные = {р.key for р in старые}
        блоки += [р.lines for р in готовые if р.key not in известные]

    непустые = [обрезанный for блок in блоки if (обрезанный := _обрезать(блок))]
    return "\n\n".join("\n".join(блок) for блок in непустые) + "\n"
