"""Бенчмарк набора поз в `results/` — чем подтверждается раздел 5.2.

Раздел «Скор различает положение лиганда в кармане» держится на трёх утверждениях:
скор нативной позы максимален, ранговая корреляция скора с отклонением от кристалла
отрицательна и велика, а доля поз с ключевой водородной связью падает с ростом
отклонения. До появления этого модуля ни одно из трёх не имело машинного источника:
сверка чисел находила корреляцию только в нашем же `docs/metrics.md`
и ставила вердикт «источник документ» — подтверждение слабее данных.
Уровня значимости не было и там.

**Про ранг нативной позы говорится осторожно, и это не придирка.** Критерий готовности
 Скор утверждает «нативное положение получает 1.0 и ранг 1», но ранг 1
даёт правило разрешения ничьих, а не превосходство скора: максимальное значение делят
несколько поз, и первой в файле стоит нативная. Поэтому отчёт печатает и ранг,
и **сколько поз делят максимум** — из двух чисел видно, чем именно обеспечен ранг
.

Модуль ничего не решает: он берёт то, что уже посчитано в папке прогона, и кладёт
в файл, на который может сослаться текст.
"""

from __future__ import annotations

import math
from pathlib import Path
from typing import Final

from evaluation.stats import spearman, spearman_permutation_p
from experiments.layout import POSE_BENCHMARK_CSV, POSE_BENCHMARK_MD
from experiments.metrics import read_metrics
from experiments.ranking import read_ranking
from experiments.results_io import Строка
from experiments.results_io import записать as _записать_отчёт
from experiments.run_io import read_molecule_props
from experiments.runs import read_passport
from kinase_ifp.config import RMSD_BIN_EDGES_A, RMSD_BIN_LABELS

ЗАГОЛОВОК: Final[str] = "Бенчмарк набора поз"
КОМАНДА: Final[str] = "python scripts/build_pose_report.py --run <run_id>"

# Колонка скора, по которой считается связь с отклонением. Именно она, а не
# нормированная: нормировка делит на число тяжёлых атомов, а в наборе поз это одна
# и та же молекула во всех положениях — делитель постоянный, и ранги бы не изменились,
# но утверждение текста относится к самому скору.
КОЛОНКА_СКОРА: Final[str] = "ifp_score"

# Метрика ключевой водородной связи. Имя колонки историческое: связь считается
# не по шарнирным позициям, а по позициям, где у эталона стоит донор или акцептор
#, и расхождение имени со смыслом оговорено в `docs/metrics.md`.
КОЛОНКА_СВЯЗИ: Final[str] = "hinge_hbond"

ТЕГ_RMSD: Final[str] = "rmsd_to_ref"
ТЕГ_ВИДА: Final[str] = "pose_kind"
ВИД_НАТИВНОЙ: Final[str] = "native"


class PoseReportError(RuntimeError):
    """Бенчмарк набора поз построить нечем."""


def _метка_бина(rmsd: float) -> str:
    """Метка бина по границам конфигурации — те же группы, что на рисунке 1."""
    низ, верх = RMSD_BIN_EDGES_A
    if rmsd < низ:
        return RMSD_BIN_LABELS[0]
    if rmsd <= верх:
        return RMSD_BIN_LABELS[1]
    return RMSD_BIN_LABELS[2]


def строки(run_dir: Path, приставка: str = "") -> list[Строка]:
    """Числа раздела 5.2 по одному набору поз.

    Прогон обязан быть набором поз: у генерации нет эталонной позы, отклонение
    от неё пусто по формату папки прогона, и корреляции взяться неоткуда. Отказ здесь
    лучше пустой таблицы — та выглядела бы как измеренное отсутствие связи.
    """
    паспорт = read_passport(run_dir)
    источник = str(паспорт.get("source", ""))
    свойства = read_molecule_props(run_dir, (ТЕГ_RMSD, ТЕГ_ВИДА))
    отклонения = {
        mol_id: float(теги[ТЕГ_RMSD]) for mol_id, теги in свойства.items() if ТЕГ_RMSD in теги
    }
    if not отклонения:
        raise PoseReportError(
            f"{run_dir.name}: ни у одной молекулы нет {ТЕГ_RMSD} (source={источник!r}) — "
            "бенчмарк поз строится только по набору поз, у генерации эталонной позы нет"
        )

    ранжирование = {строка["mol_id"]: строка for строка in read_ranking(run_dir)}
    метрики = {строка["mol_id"]: строка for строка in read_metrics(run_dir)}

    общие = [mol_id for mol_id in отклонения if mol_id in ранжирование]
    if len(общие) < 2:
        raise PoseReportError(f"{run_dir.name}: меньше двух поз со скором и отклонением")

    скоры = [float(ранжирование[mol_id][КОЛОНКА_СКОРА]) for mol_id in общие]
    отклонения_ряд = [отклонения[mol_id] for mol_id in общие]

    ро = spearman(скоры, отклонения_ряд)
    if math.isnan(ро):
        raise PoseReportError(
            f"{run_dir.name}: скор одинаков у всех поз — связь с отклонением не определена"
        )
    уровень, перестановок = spearman_permutation_p(скоры, отклонения_ряд)

    максимум = max(скоры)
    делят_максимум = sum(1 for значение in скоры if значение == максимум)

    нативные = [
        mol_id for mol_id, теги in свойства.items() if теги.get(ТЕГ_ВИДА) == ВИД_НАТИВНОЙ
    ]
    if len(нативные) != 1:
        raise PoseReportError(
            f"{run_dir.name}: нативных поз {len(нативные)}, а должна быть ровно одна"
        )
    нативная = нативные[0]

    # Приставка нужна, когда в одном файле стоят две мишени: без неё строки
    # «корреляция скора с отклонением» сольются, и сравнить будет нечего —
    # а ради сравнения второй набор поз и считался (`C.2` плана подачи).
    имя = f"{приставка}: " if приставка else ""

    собранные = [
        Строка(f"{имя}поз в наборе", len(общие), "поз"),
        Строка(f"{имя}скор нативной позы", float(ранжирование[нативная][КОЛОНКА_СКОРА]), "скор"),
        Строка(f"{имя}наибольший скор в наборе", максимум, "скор"),
        Строка(f"{имя}поз с наибольшим скором", делят_максимум, "поз"),
        Строка(f"{имя}ранг нативной позы", float(ранжирование[нативная]["rank"]), "ранг"),
        Строка(f"{имя}корреляция скора с отклонением", ро, "ро Спирмена"),
        Строка(f"{имя}уровень значимости корреляции", уровень, "p"),
        Строка(f"{имя}перестановок в тесте", перестановок, "перестановок"),
    ]

    # Доли ключевой связи по тем же бинам, что на рисунке 1: картинка и текст обязаны
    # показывать одни группы, иначе читатель сравнивает несравнимое.
    for метка in RMSD_BIN_LABELS:
        свои = [
            mol_id
            for mol_id in общие
            if _метка_бина(отклонения[mol_id]) == метка and mol_id in метрики
        ]
        значения = [
            float(метрики[mol_id][КОЛОНКА_СВЯЗИ])
            for mol_id in свои
            if str(метрики[mol_id].get(КОЛОНКА_СВЯЗИ, "")).strip() != ""
        ]
        собранные.append(Строка(f"{имя}поз в бине {метка}", len(значения), "поз"))
        собранные.append(
            Строка(
                f"{имя}доля с ключевой связью, {метка}",
                sum(значения) / len(значения) if значения else float("nan"),
                "доля",
            )
        )
    return собранные


def записать(строки_отчёта: list[Строка], каталог: Path) -> tuple[Path, Path]:
    """Кладёт оба файла в `results/` и возвращает пути к ним."""
    return _записать_отчёт(
        строки_отчёта,
        каталог,
        имя_md=POSE_BENCHMARK_MD,
        имя_csv=POSE_BENCHMARK_CSV,
        заголовок=ЗАГОЛОВОК,
        откуда=КОМАНДА,
    )
