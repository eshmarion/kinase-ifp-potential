"""Имена производных файлов: папка прогона и выход этапа.

Единственное место, где эти имена объявлены. Раньше у них не было хозяина:
`run_io` писал прогон, `ranking` считал скор, `report` собирал таблицу, и каждый
объявлял то, что понадобилось ему. Совпадения никем не проверялись, а `runs.py`
брал `RUN_JSON` у `report.py` — вместе с pandas, которого в облачном образе DiffSBDD
нет: сэмплер упал бы уже на удалённой машине.

Отсюда главное свойство модуля: **только stdlib, ни одного тяжёлого импорта**. Имена
должны читаться и там, где нет ни pandas, ни MDAnalysis, ни prolif, ни rdkit — это
проверяется тестом `tests/test_layout.py`, а не держится на памяти.

Состав папки прогона нужен сразу нескольким модулям, а не одному, поэтому каждое
имя объявлено здесь, а не по месту использования.

**Выход этапа добавлен позже.** До этого модуль отвечал только
за папку прогона, а имена того, что из прогонов производится, жили строками в пяти
местах сразу: `before_after.{md,csv}` в `report`, имена рисунков в `figures`,
`panels.csv` в `kinase_ifp.config`. Правило завели для папки прогона, и на соседнюю
полку оно сразу не распространилось. Плата названа честно: модуль больше не «про
папку прогона», он про **все** файлы, которые производит код и на которые
опираются результаты.
"""

from __future__ import annotations

from typing import Final

# Что производит генератор молекул: сам SDF и отбраковка.
MOLECULES_SDF: Final[str] = "molecules.sdf"
FAILURES_CSV: Final[str] = "failures.csv"

# Паспорт прогона. Без него прогон считается несуществующим.
RUN_JSON: Final[str] = "run.json"

# Метрики по молекулам и их агрегаты с доверительными интервалами.
METRICS_CSV: Final[str] = "metrics_per_molecule.csv"
SUMMARY_CSV: Final[str] = "metrics_summary.csv"

# Переранжирование по IFP-скору.
RANKING_CSV: Final[str] = "ranking.csv"

# Метрики плана Б: ROC-AUC, top-1 и монотонность скора по RMSD. Лежат
# в папке прогона рядом с `ranking.csv`, потому что считаются по одному прогону
# и меняются вместе с ним.
PLAN_B_METRICS_JSON: Final[str] = "plan_b_metrics.json"

# Реестр прогонов. Лежит **рядом** с папками прогонов, а не внутри
# папки одного из них: это опись всего каталога `runs/`, и искать его внутри
# `runs/<run_id>/` бесполезно.
INDEX_CSV: Final[str] = "index.csv"

# Чем произведён прогон. Значение поля `source` в паспорте, и оно же решает, какие
# колонки таблицы метрик применимы: контрольные метрики считаются только при
# генерации, на наборе поз они вырождены. Обе константы были объявлены дважды —
# в `run_io` и в `report`, — и это ровно тот случай, ради которого модуль заведён:
# имя, нужное нескольким модулям, не может принадлежать одному из них.
SOURCE_LOCAL_POSES: Final[str] = "local-poses"
SOURCE_DIFFSBDD: Final[str] = "diffsbdd"

# Чем задан карман при генерации. `ref-ligand` — по кристаллическому
# лиганду, штатный способ из README DiffSBDD; `pocket-ids` — явным списком остатков
# KLIFS. Значения жили в `scripts/modal_sample.py`, но 16.09 понадобились реестру:
# прогон на `pocket-ids` — отрицательный контроль, и в таблицу «было/стало» он идти
# не должен (`main_line_runs`). Какой из двух способов рабочий, проект не решил
#; здесь объявлены оба имени, а не выбран один.
POCKET_MODE_REF_LIGAND: Final[str] = "ref-ligand"
POCKET_MODE_POCKET_IDS: Final[str] = "pocket-ids"

# Чем заканчивается строка в наших CSV. Модуль `csv` из стандартной библиотеки пишет
# `\r\n` — так требует RFC 4180, — а pandas и `.gitattributes` держат `\n`. Пока
# `runs/` лежал вне git, разница была невидима; с 25.08 прогоны коммитятся
#, и файл, записанный одним способом, а сохранённый другим, виден
# в diff как изменённый целиком — сто строк вместо ни одной. Читатели CSV принимают
# оба варианта, поэтому выбран тот, что совпадает с остальным репозиторием.
CSV_EOL: Final[str] = "\n"

# Выход этапа: то, что собирается из прогонов. Лежит в `results/`, а не в `runs/`:
# это уже не прогон, а его изложение. Имя здесь по той же причине, что и выше:
# на файл ссылаются несколько модулей сразу.
BEFORE_AFTER_MD: Final[str] = "before_after.md"
BEFORE_AFTER_CSV: Final[str] = "before_after.csv"

# Сводка различительной способности по мишеням: медианы и размахи по наборам поз
# каждой мишени. Отдельно от `before_after.*`, потому что отвечают на другой вопрос:
# не «что дал отбор», а «различает ли мера размещение вообще».
DISCRIMINATION_SUMMARY_MD: Final[str] = "pose_discrimination.md"
DISCRIMINATION_SUMMARY_CSV: Final[str] = "pose_discrimination.csv"

# Измерения по всей базе KLIFS: состав выборки и знаменатель скора. Они не из
# прогонов, но подчиняются тому же правилу: у числа одно место, откуда его берут.
# Раньше эти числа только печатались на экран, и сослаться было не на что.
KLIFS_BASE_MD: Final[str] = "klifs_base.md"
KLIFS_BASE_CSV: Final[str] = "klifs_base.csv"

# Бенчмарк набора поз: связь скора с отклонением положения от кристалла. Раньше
# главное число здесь — ранговая корреляция — подтверждалось только прозой
# документа, а не данными. Имя здесь по той же причине, что у соседей.
POSE_BENCHMARK_MD: Final[str] = "pose_benchmark.md"
POSE_BENCHMARK_CSV: Final[str] = "pose_benchmark.csv"

# Кривая компромисса «доля отбора — качество».
SWEEP_CSV: Final[str] = "sweep_top_fraction.csv"

# Пересчёт по правилам KLIFS и пять усиливающих проверок. Имена стояли литералами
# в двух модулях сразу; объявлены здесь, как и прочие имена файлов, чтобы сверка
# и сборка не разошлись при переименовании.
RESCORE_SUMMARY_CSV: Final[str] = "klifs_rules_rescore.csv"
CHECKS_SUMMARY_CSV: Final[str] = "thesis_checks.csv"

# Рисунки раздела «Результаты» и машинная опись их панелей. Номер в имени
# файла — не номер в тексте: нумерация в курсовой сквозная и присваивается по порядку
# **собранных** рисунков, поэтому несобранный второй не оставляет дыры.
FIGURE_SIMILARITY: Final[str] = "fig1_ifp_similarity.png"
FIGURE_CONTROL: Final[str] = "fig2_control_metrics.png"
FIGURE_PIPELINE: Final[str] = "fig3_pipeline.png"
FIGURE_BASE: Final[str] = "fig4_klifs_base.png"
FIGURE_REFINEMENT: Final[str] = "fig5_refinement.png"
FIGURE_SELECTION: Final[str] = "fig6_selection_size.png"
FIGURE_POSE_SCORES: Final[str] = "fig7_pose_scores.png"
FIGURE_IFP_MAP: Final[str] = "fig8_ifp_map.png"
FIGURE_STATES: Final[str] = "fig9_states.png"
PANELS_CSV: Final[str] = "panels.csv"

# Числа, которые называет подпись рисунка: поголовья, доли, медианы. Заведён после
# того, как подписи принесли числа `2962` и `313`, у которых машинного источника
# не было нигде — `panels.csv` описывает только объёмы панелей. Подпись обязана
# опираться на измерение так же, как абзац текста.
FIGURE_FACTS_CSV: Final[str] = "facts.csv"
FIGURES_README: Final[str] = "README.md"

# Чем нарисованы рисунки. `matplotlib` намеренно **не** внесён
# в `runs.NUMERIC_LIBRARIES`: тот отвечает на «чем посчитаны числа», а рисовалка
# ничего не считает. Но вид рисунка от её версии зависит — кегли умолчаний, усы
# `whis`, имя аргумента `tick_labels`, переименованного в 3.9, — и без этого файла
# ответить «на чём собран рисунок» нечем. Лежит рядом с рисунками, а не в паспорте
# прогона: это свойство выхода этапа, а не прогона.
FIGURES_ENVIRONMENT_JSON: Final[str] = "environment.json"
