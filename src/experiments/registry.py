"""Реестр прогонов `runs/index.csv`.

Реестр — единственный источник правды о том, какие прогоны существуют: глазами
по папкам никто не ходит, а сборка отчёта берёт список прогонов отсюда.

Строка реестра собирается из паспорта прогона и того, что физически лежит
в папке, а не из памяти о том, что запускали. Поэтому реестр можно пересобрать
целиком в любой момент: он производный, а не первичный.

Статусы:

* `generated` — есть паспорт, скор ещё не считался;
* `scored` — рядом появился `ranking.csv`, то есть прогон переранжирован;
* `failed` — папки нет паспорта, то есть описать эксперимент нечем.

Провалившийся прогон именно записывается, а не пропускается: молча исчезнувшая папка
выглядит как «эксперимента не было», и о нём вспоминают в день сборки таблицы.

**Колонка `molecules` заведена 18.09**. До неё отсутствие `molecules.sdf`
давало `failed` наравне с отсутствием паспорта, и прогон, у которого молекулы намеренно
оставлены у автора, выпадал из реестра, а следом из таблицы и рисунков — без единого
сообщения. Теперь это отдельный признак: `in-git` — молекулы лежат здесь и по ним можно
пересчитать скор и метрики; `local-only` — их тут нет, а числа берутся из `ranking.csv`
и `metrics_per_molecule.csv` как есть.
"""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Any, Final

# Имена файлов берутся у `layout`, а не у `report`: тот тянет pandas, а реестру
# он не нужен — CSV читается и пишется модулем `csv`.
from experiments.layout import (
    CSV_EOL,
    INDEX_CSV,
    METRICS_CSV,
    POCKET_MODE_POCKET_IDS,
    RANKING_CSV,
)
from experiments.runs import RunError, exists, has_molecules, read_passport

# Заголовок из формата реестра прогонов, порядок колонок обязателен: на него смотрит отчёт.
INDEX_COLUMNS: Final[tuple[str, ...]] = (
    "run_id",
    "date",
    "pdb_id",
    "source",
    "condition",
    "guidance_scale",
    "seed",
    "n_returned",
    "platform",
    "status",
    "path",
    "molecules",
)

# Значения колонки `molecules`.
MOLECULES_IN_GIT: Final[str] = "in-git"
MOLECULES_LOCAL_ONLY: Final[str] = "local-only"

STATUS_GENERATED: Final[str] = "generated"
STATUS_SCORED: Final[str] = "scored"
STATUS_FAILED: Final[str] = "failed"


class RegistryError(RuntimeError):
    """Реестр не удалось обновить."""


def describe_run(run_dir: Path, runs_dir: Path) -> dict[str, Any]:
    """Собирает строку реестра по папке прогона.

    `path` пишется относительно `runs/`: реестр должен переживать переезд каталога
    на другую машину, а абсолютный путь этого не переживает.
    """
    строка: dict[str, Any] = dict.fromkeys(INDEX_COLUMNS, "")
    строка["run_id"] = run_dir.name
    строка["path"] = run_dir.relative_to(runs_dir).as_posix()

    if not exists(run_dir):
        строка["status"] = STATUS_FAILED
        return строка

    try:
        паспорт = read_passport(run_dir)
    except RunError:
        строка["status"] = STATUS_FAILED
        return строка

    выборка = паспорт.get("sampling", {})
    строка.update(
        run_id=паспорт["run_id"],
        date=str(паспорт.get("created_utc", ""))[:10],
        pdb_id=паспорт.get("target", {}).get("pdb_id", ""),
        source=паспорт["source"],
        guidance_scale=выборка.get("guidance_scale", ""),
        seed=выборка.get("seed", ""),
        n_returned=выборка.get("n_returned", ""),
        platform=паспорт.get("platform", ""),
        condition=_conditions(run_dir),
        status=STATUS_SCORED if (run_dir / RANKING_CSV).is_file() else STATUS_GENERATED,
        molecules=MOLECULES_IN_GIT if has_molecules(run_dir) else MOLECULES_LOCAL_ONLY,
    )
    return строка


def _conditions(run_dir: Path) -> str:
    """Условия эксперимента, встреченные в метриках прогона.

    Условие живёт в `metrics_per_molecule.csv`, а не в паспорте: один прогон
    может дать несколько условий — например `baseline` и `rerank-top20`. Пока метрик
    нет, колонка пуста, и это не ошибка: до расчёта скора их и не должно быть.
    """
    метрики = run_dir / METRICS_CSV
    if not метрики.is_file():
        return ""
    with метрики.open(encoding="utf-8", newline="") as файл:
        значения = {
            строка.get("condition", "").strip()
            for строка in csv.DictReader(файл)
            if строка.get("condition", "").strip()
        }
    return ";".join(sorted(значения))


def read_index(index_path: Path) -> list[dict[str, Any]]:
    """Читает реестр; отсутствующий файл — пустой список, а не ошибка."""
    if not index_path.is_file():
        return []
    with index_path.open(encoding="utf-8", newline="") as файл:
        return list(csv.DictReader(файл))


def write_index(index_path: Path, rows: list[dict[str, Any]]) -> Path:
    """Пишет реестр целиком, отсортировав строки по `run_id`."""
    index_path.parent.mkdir(parents=True, exist_ok=True)
    with index_path.open("w", encoding="utf-8", newline="") as файл:
        писатель = csv.DictWriter(файл, fieldnames=list(INDEX_COLUMNS), lineterminator=CSV_EOL)
        писатель.writeheader()
        писатель.writerows(sorted(rows, key=lambda строка: строка["run_id"]))
    return index_path


def register_run(run_dir: Path, runs_dir: Path) -> dict[str, Any]:
    """Добавляет один прогон в реестр и возвращает его строку.

    Повторная регистрация того же `run_id` — ошибка, а не перезапись: расходящиеся
    строки об одном прогоне означают, что папку подменили, и молча принять новую
    версию значит потерять след старой.
    """
    index_path = runs_dir / INDEX_CSV
    строки = read_index(index_path)
    if any(строка["run_id"] == run_dir.name for строка in строки):
        raise RegistryError(
            f"прогон {run_dir.name} уже в реестре {index_path}; повторная регистрация "
            "запрещена — новый запуск получает новый run_id"
        )

    строка = describe_run(run_dir, runs_dir)
    write_index(index_path, [*строки, строка])
    return строка


def refresh_run(run_dir: Path, runs_dir: Path) -> dict[str, Any]:
    """Обновляет строку уже заведённого прогона и возвращает её.

    Нужна потому, что состояние прогона меняется по ходу работы: после генерации он
    `generated`, после переранжирования — `scored`, а условия появляются
    вместе с метриками. Строка реестра производная, и пересчитать её из файлов —
    не перезапись прогона: неизменяемость защищает молекулы и паспорт, а не опись.

    От `register_run` отличается направлением проверки: та отказывается заводить
    прогон дважды, эта — обновлять несуществующий. Вторая строка с тем же `run_id`
    не появляется ни при каком порядке вызовов.
    """
    index_path = runs_dir / INDEX_CSV
    строки = read_index(index_path)
    прочие = [строка for строка in строки if строка["run_id"] != run_dir.name]
    if len(прочие) == len(строки):
        raise RegistryError(
            f"прогона {run_dir.name} нет в реестре {index_path}; сначала заведите его "
            "register_run или пересоберите реестр целиком scripts/index_runs.py"
        )

    строка = describe_run(run_dir, runs_dir)
    write_index(index_path, [*прочие, строка])
    return строка


def scored_runs(runs_dir: Path) -> list[Path]:
    """Папки прогонов, готовых к отчёту: строки реестра со статусом `scored`.

    С 24.08 список прогонов для таблицы «было/стало» берётся отсюда, а не из
    аргументов командной строки: реестр знает про все прогоны сразу,
    а руки — только про те, что вспомнили.

    Берутся именно `scored`: у `generated` нет ни метрик, ни `ranking.csv`
, и колонка такого прогона вышла бы пустой. Реестр не пересобирается —
    читается как есть: пересборка требует `runs/`, а отчёт должен собираться и там,
    где лежит только опись.
    """
    строки = read_index(runs_dir / INDEX_CSV)
    return [
        runs_dir / строка["path"]
        for строка in строки
        if строка.get("status") == STATUS_SCORED
    ]


def main_line_runs(runs_dir: Path, pdb_id: str | None = None) -> list[Path]:
    """Прогоны основной линии: по одному на источник — для таблицы «было/стало».

    Правило: **прогон, помеченный в паспорте как основной; если такого нет — самый
    полный прогон источника, а среди равных по полноте — самый свежий**. Полнота —
    `sampling.n_requested`, свежесть — `created_utc`.

    **Метка `main_line` стоит выше полноты и заведена 18.09** (`runs.record_main_line`,
    Повод: прогон, поставленный ради сужения доверительных интервалов,
    оказался втрое полнее прежнего и молча занял его место — а по прежнему уже был
    написан раздел «Результаты». Правило пересчитывает выбор при каждом запуске,
    поэтому «какой прогон полнее» и «каким прогоном представлена работа» разошлись;
    метка разводит эти вопросы и ничего не меняет, пока её никто не поставил.
    Два помеченных прогона одного источника — отказ, а не молчаливый выбор одного
    из них.

    Мишень входит в **ключ группировки**: прогоны разных киназ становятся отдельными
    колонками и друг друга не вытесняют. Необязательный `pdb_id` сужает отбор до одной
    мишени и по умолчанию выключен — **включать его значит решить, что вторая киназа
    в таблицу работы не входит, а это решение авторов разделов, не реестра**.
    Историю обеих половин правила см. ниже.

    Прежняя редакция этого места отбирала внутри одной мишени (`pdb_id`, мишень работы
    `MAIN_TARGET_PDB_ID`). До 16.09 фильтра не было, потому что мишень в `runs/` была
    одна; в тот день появился набор поз второй мишени (`3war`, пункт `C.2` плана подачи),
    и правило «среди равных по полноте — самый свежий» немедленно увело бы на него
    и рисунок 1, и колонку `local-poses` таблицы: прогон свежее, а `n_requested` тот же.
    Числа при этом остались бы верными, а подпись — прежней, то есть подмена мишени
    прошла бы молча. Ту же подмену сняла и группировка по паре «источник × мишень»,
    заведённая 17.09 независимо, поэтому фильтр из умолчания убран: одной защиты
    достаточно, а вторая молча решала бы вопрос о составе таблицы.

    Зачем не все `scored` подряд. К вечеру 24.08 в реестре шесть посчитанных прогонов,
    и прямой отбор давал двенадцать колонок: два набора поз дают побитово одинаковые
    числа (сид один, различался только пакет мишени, которым считали), а две пробы
    по 20 молекул отвечали на методический вопрос `В-13` и в главной таблице им не место.

    Почему полнота идёт раньше свежести. Самый свежий прогон `diffsbdd` — как раз проба
    из 20 молекул на проигравшем способе задать карман; попав в таблицу основной
    колонкой, он представлял бы работу худшим из измеренных вариантов. Кроме того,
    таблица сравнивает распределения, а межквартильный размах по 20 молекулам и по 95 —
    величины разной надёжности, и ставить их соседними колонками значит сравнивать
    несравнимое. Пробы отсеиваются этим правилом сами, без списка исключений.

    **Почему способ задания кармана идёт раньше обоих.** 16.09 защита полнотой перестала
    работать: прогон на `pocket-ids` сделан на тех же 100 молекулах, что и основной,
    и по свежести вытеснил его из таблицы — работа была бы представлена своим
    отрицательным контролем. Полнота здесь не помогает по построению: контроль ставят
    на том же объёме, иначе он не контроль.

    Выбор между двумя способами здесь **не делается** — он остаётся открытым,
    и решать её не реестру. Правило слабее: прогон, у которого способ назван как
    `pocket-ids`, не представляет источник в главной таблице, потому что он поставлен
    ради сравнения с ней. Прогон без поля `pocket_mode` представляет источник
    по-прежнему.

    **Почему в ключе стоит мишень.** До 17.09 правило группировало прогоны по одному
    источнику и о мишени не знало вовсе — потому что мишень в проекте была одна.
    Первый же набор поз на второй киназе (`6fnk`, пункт `C.2` плана подачи) вытеснил
    из таблицы набор поз основной мишени: тот же источник, та же полнота, свежее дата.
    Таблица показала бы числа чужой киназы под заголовком, который текст относит
    к `6tgu`, и заметить это было бы нечем. Это тот же отказ, что с отрицательным
    контролем 16.09, только уровнем выше: сравниваемое и представляющее работу опять
    оказались в одной ячейке.

    Мишень поэтому входит в ключ группировки, а не в ключ сравнения: прогоны разных
    мишеней друг друга не вытесняют, а становятся отдельными колонками. **Считать ли
    вторую мишень частью главной таблицы — решение не реестра**, и правило его
    не принимает: оно лишь перестаёт подменять одну мишень другой молча.

    Паспорта читаются с диска, хотя `scored_runs` намеренно обходится одной описью:
    ни полноты, ни точного времени в формате реестра прогонов нет, а расширять его двумя колонками
    ради этого дороже, чем прочитать несколько JSON-файлов — папки прогонов всё равно
    будут прочитаны следующим шагом, при сборке колонок.
    """
    # Ключ словаря — пара «источник × мишень», ключ сравнения — тройка «способ задания
    # кармана, полнота, свежесть» именно в этом порядке, см. докстроку. Три правки
    # 16–17.09 заведены независимо и об одном и том же: прогон, поставленный ради
    # сравнения, не должен представлять работу в главной таблице. Отрицательный
    # контроль `pocket-ids` отсекается ключом сравнения, чужая мишень — ключом
    # группировки, а фильтр `pdb_id` оставляет в таблице только мишень работы.
    лучшие: dict[tuple[str, str], tuple[tuple[int, int, int, str], Path]] = {}
    помеченные: dict[tuple[str, str], Path] = {}
    for папка in scored_runs(runs_dir):
        try:
            паспорт = read_passport(папка)
        except RunError as ошибка:
            raise RegistryError(
                f"{папка}: реестр числит прогон посчитанным, но паспорт не читается "
                f"({ошибка}). Пересоберите реестр scripts/index_runs.py"
            ) from ошибка

        # Мишень берётся из паспорта, а не из имени папки: `make_run_id` не кодирует
        # сид, имена разводятся суффиксами, и позиционный разбор имени рано или поздно
        # уводит на чужую мишень (то же правило, что у `runs.target_for_run`).
        мишень = str(паспорт.get("target", {}).get("pdb_id", ""))
        if pdb_id is not None and мишень != pdb_id:
            continue

        источник = str(паспорт["source"])
        сэмплинг = паспорт.get("sampling", {})
        помечен = bool(паспорт.get("main_line"))
        if помечен:
            прежняя_метка = помеченные.setdefault((источник, мишень), папка)
            if прежняя_метка != папка:
                raise RegistryError(
                    f"Метку «основной» несут сразу два прогона одного источника: "
                    f"{прежняя_метка.name} и {папка.name}. Работа представляется одним "
                    "прогоном на источник — снимите метку с лишнего "
                    "(runs.record_main_line с main_line=False)"
                )
        ключ = (
            int(помечен),
            int(сэмплинг.get("pocket_mode") != POCKET_MODE_POCKET_IDS),
            int(сэмплинг.get("n_requested") or 0),
            str(паспорт.get("created_utc", "")),
        )
        прежний = лучшие.get((источник, мишень))
        if прежний is None or ключ > прежний[0]:
            лучшие[(источник, мишень)] = (ключ, папка)

    return [папка for _, папка in sorted(лучшие.values(), key=lambda пара: пара[1].name)]


def rebuild_index(runs_dir: Path) -> list[dict[str, Any]]:
    """Пересобирает реестр по содержимому `runs/` и возвращает его строки.

    Пересборка не считается перезаписью прогона: сами папки не трогаются, а реестр
    производный — он и должен восстанавливаться из них в любой момент.
    """
    if not runs_dir.is_dir():
        raise RegistryError(f"нет каталога прогонов {runs_dir}")

    строки = [
        describe_run(папка, runs_dir)
        for папка in sorted(runs_dir.iterdir())
        if папка.is_dir()
    ]
    write_index(runs_dir / INDEX_CSV, строки)
    return строки
