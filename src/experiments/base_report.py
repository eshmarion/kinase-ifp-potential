"""Измерения по всей базе KLIFS — в файл, на который может сослаться текст.

`kinase_ifp.base_stats` считает состав выгрузки (`B.2`) и знаменатель скора по всем
эталонам базы (`B.4`), но только печатает их. Числу в курсовой печать источником
не является: `scripts/check_numbers.py` берёт источники **закрытым списком** файлов,
и всё, чего в этом списке нет, при сверке чисел считается неподтверждённым.

Поэтому здесь ровно одно: разложить обе структуры в плоские строки «показатель —
значение» и записать их двумя файлами, как это уже сделано для таблицы «было/стало».
Своей арифметики модуль не содержит: производные величины берутся у самих структур.
"""

from __future__ import annotations

from pathlib import Path

from experiments.layout import KLIFS_BASE_CSV, KLIFS_BASE_MD
from experiments.results_io import Строка
from experiments.results_io import записать as _записать_отчёт
from kinase_ifp.base_stats import DatasetComposition, Distribution, ReferenceBits

ЗАГОЛОВОК = "Измерения по базе KLIFS"
КОМАНДА = "python scripts/build_klifs_base_report.py"


def _распределение(распределение: Distribution, подпись: str) -> list[Строка]:
    """Квартили колонки и то, сколько значений проходит порог отбора."""
    return [
        # Знаменатель доли, а не украшение: у разрешения значение указано не у всех
        # структур выгрузки (13843 из 14068), и «доля прошедших 0.9210» без этой
        # строки считалась бы от неверного числа всяким, кто решит её пересчитать.
        Строка(f"{подпись}: значений", распределение.count, "структур"),
        Строка(f"{подпись}: минимум", распределение.minimum, "величина"),
        Строка(f"{подпись}: первый квартиль", распределение.q1, "величина"),
        Строка(f"{подпись}: медиана", распределение.median, "величина"),
        Строка(f"{подпись}: третий квартиль", распределение.q3, "величина"),
        Строка(f"{подпись}: максимум", распределение.maximum, "величина"),
        Строка(f"{подпись}: порог отбора", распределение.threshold, "величина"),
        Строка(f"{подпись}: проходит порог", распределение.passing, "структур"),
        Строка(f"{подпись}: доля прошедших", распределение.passing_share, "доля"),
    ]


def строки(состав: DatasetComposition, эталоны: ReferenceBits) -> list[Строка]:
    """Все числа обоих измерений одним плоским списком."""
    собранные = [
        Строка("выгружено структур", состав.downloaded, "структур"),
        Строка("прошло фильтры отбора", состав.selected, "структур"),
        Строка("киназ в выгрузке", состав.kinases, "киназ"),
        Строка("эталонных отпечатков", состав.fingerprints, "отпечатков"),
        Строка("структур с лигандом", состав.with_ligand, "структур"),
        Строка("из них с нуклеотидом", состав.nucleotide, "структур"),
        Строка("доля нуклеотидных", состав.nucleotide_share, "доля"),
    ]
    собранные += _распределение(состав.resolution, "разрешение")
    собранные += _распределение(состав.quality, "оценка качества")

    собранные += [
        Строка("эталонов в расчёте", эталоны.structures, "структур"),
        Строка("направленных бит: медиана", эталоны.directed_median, "бит"),
        Строка("направленных бит: среднее", эталоны.directed_mean, "бит"),
        Строка("направленных бит: минимум", эталоны.directed_minimum, "бит"),
        Строка("направленных бит: максимум", эталоны.directed_maximum, "бит"),
        Строка("структур с малым числом направленных", эталоны.few_directed, "структур"),
        Строка("их доля", эталоны.few_directed_share, "доля"),
        Строка("бит всего", эталоны.total_bits, "бит"),
        Строка("доля гидрофобных бит", эталоны.hydrophobic_share, "доля"),
        Строка("позиций кармана в контакте: медиана", эталоны.positions_median, "позиций"),
        Строка(
            "из них с направленным контактом: медиана",
            эталоны.directed_positions_median,
            "позиций",
        ),
    ]
    собранные += [
        Строка(f"бит типа {тип}", количество, "бит") for тип, количество in эталоны.bits_by_type
    ]
    return собранные


def записать(строки_отчёта: list[Строка], каталог: Path) -> tuple[Path, Path]:
    """Кладёт оба файла в `results/` и возвращает пути к ним."""
    return _записать_отчёт(
        строки_отчёта,
        каталог,
        имя_md=KLIFS_BASE_MD,
        имя_csv=KLIFS_BASE_CSV,
        заголовок=ЗАГОЛОВОК,
        откуда=КОМАНДА,
    )
