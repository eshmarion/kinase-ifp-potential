"""Общая запись измерений в `results/`.

Отчётов, которые кладут в текст плоский список «показатель — значение», уже два:
измерения по базе KLIFS (`base_report`) и бенчмарк набора поз (`pose_report`). Форма
у них одна, и заводить её дважды нельзя: разойдутся не только отступы, но и способ
печати целых — а по этому числу сверка ищет значение в источниках. Один раз
напечатанное `14068.0` вместо `14068` делает число текста неподтверждённым.

Здесь только форма. Что измерять и как это называть — дело самих отчётов.
"""

from __future__ import annotations

import csv
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Final

from experiments.layout import CSV_EOL

ЗАГОЛОВОК: tuple[str, str, str] = ("показатель", "значение", "единица")


@dataclass(frozen=True)
class Строка:
    """Одна измеренная величина: что это, сколько и в чём выражено."""

    показатель: str
    значение: float
    единица: str


# Насколько запись имеет право отличаться от величины. Полпроцента — это заметно
# меньше, чем разница между соседними значениями любой нашей меры, и заметно больше,
# чем ошибка четвёртого знака у числа порядка единицы.
ДОПУСТИМАЯ_ОШИБКА_ЗАПИСИ: Final[float] = 0.005


def как_текст(значение: float) -> str:
    """Целое печатается целым: «14068 структур», а не «14068.0».

    Сверка чисел ищет значение текста среди значений источников, и запись
    с лишней дробной частью там не находится. Дробное печатается четырьмя знаками —
    столько же несут `before_after.csv` и `metrics_summary.csv`.

    **Число, у которого четыре знака съедают значащие цифры, печатается научной
    записью.** Четыре знака превращали любое p меньше 0.0001
    в «0.0000», и это не округление, а подмена значения — p нулём не бывает. Величина
    вида 1.37·10⁻⁴ при этом становилась «0.0001», то есть теряла все значащие цифры,
    кроме одной. Текст такие величины пишет научной записью («4.1·10⁻¹⁰»), и сверка
    их не подтверждала.

    Критерий — не порог по величине, а потеря точности: если округление до четырёх
    знаков уводит число больше чем на полпроцента, запись врёт и берётся научная.
    Порог по величине пришлось бы подбирать под каждую меру, а этот вопрос задаёт
    сам себе.

    Значащих в научной записи семь, столько же, сколько несут прочие выгрузки. Это
    не запас: сверка огрубляет источник до точности текста, и на ровной половине
    округление уходит в разные стороны. Настоящее 1.4496·10⁻⁴, записанное короче как
    «1.450e-04», огрубляется до 1.5·10⁻⁴, тогда как автор пишет 1.4·10⁻⁴ — и число
    текста перестаёт подтверждаться собственным источником.
    """
    число = float(значение)
    if число != число:  # NaN: величина неприменима, и это не ноль
        return "—"
    if число.is_integer():
        return str(int(число))
    округлённое = round(число, 4)
    потеряно = abs(округлённое - число) > abs(число) * ДОПУСТИМАЯ_ОШИБКА_ЗАПИСИ
    return f"{число:.6e}" if потеряно else f"{число:.4f}"


def отчёт_markdown(строки: Sequence[Строка], заголовок: str, откуда: str) -> str:
    """Таблица для чтения человеком; `откуда` — команда, которой файл пересобирается."""
    шапка = [
        f"# {заголовок}",
        "",
        "Файл производный: собирается командой",
        f"`{откуда}`.",
        "Правится измерение или его источник, а не он.",
        "",
        "| Показатель | Значение | Единица |",
        "|---|---|---|",
    ]
    тело = [f"| {с.показатель} | {как_текст(с.значение)} | {с.единица} |" for с in строки]
    return "\n".join(шапка + тело) + "\n"


def записать(
    строки: Sequence[Строка],
    каталог: Path,
    *,
    имя_md: str,
    имя_csv: str,
    заголовок: str,
    откуда: str,
) -> tuple[Path, Path]:
    """Кладёт пару файлов и возвращает пути к ним."""
    каталог.mkdir(parents=True, exist_ok=True)

    путь_md = каталог / имя_md
    путь_md.write_text(отчёт_markdown(строки, заголовок, откуда), encoding="utf-8", newline=CSV_EOL)

    путь_csv = каталог / имя_csv
    with путь_csv.open("w", encoding="utf-8", newline="") as файл:
        писатель = csv.writer(файл, lineterminator=CSV_EOL)
        писатель.writerow(ЗАГОЛОВОК)
        for строка in строки:
            писатель.writerow([строка.показатель, как_текст(строка.значение), строка.единица])

    return путь_md, путь_csv
