def список() -> str:
    """Человекочитаемая опись этапов с метками и выходами."""
    строки = ["Этапы конвейера:", ""]
    for э in ЭТАПЫ:
        строки.append(f"  {э.имя:<14} [{э.метка:<7}] {э.описание}")
        строки.append(f"  {'':<14} команда: python {' '.join(э.команда)}")
        if э.выходы:
            строки.append(f"  {'':<14} даёт:    {', '.join(э.выходы)}")
        строки.append("")
    строки.append(f"В сверку по умолчанию входят метки: {', '.join(МЕТКИ_СВЕРКИ)}.")
    return "\n".join(строки)


def найти(имя: str) -> Этап:
    """Этап по имени; поднимает `ReproduceError`, если такого нет."""
    for э in ЭТАПЫ:
        if э.имя == имя:
            return э
    известные = ", ".join(э.имя for э in ЭТАПЫ)
    raise ReproduceError(f"этапа {имя!r} нет; известны: {известные}")


def выполнить(этап: Этап, корень: Path | None = None) -> None:
    """Запускает команду этапа в указанном каталоге репозитория."""
    где = корень or PROJECT_ROOT
    итог = subprocess.run(
        [sys.executable, *этап.команда],
        cwd=где,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if итог.returncode != 0:
        raise ReproduceError(
            f"этап {этап.имя!r} завершился с кодом {итог.returncode}:\n{итог.stderr[-2000:]}"
        )


def _ячейки(путь: Path) -> list[str]:
    """Все ячейки CSV одним списком — так сравнение не зависит от разбивки на строки."""
    with путь.open(encoding="utf-8", newline="") as f:
        return [ячейка for строка in csv.reader(f) for ячейка in строка]


def _сравнить_csv(было: Path, стало: Path) -> str | None:
    """Расхождение по значениям ячеек; числа сравниваются с допуском."""
    ячейки_было = _ячейки(было)
    ячейки_стало = _ячейки(стало)
    if len(ячейки_было) != len(ячейки_стало):
        return f"{было.name}: было {len(ячейки_было)} ячеек, стало {len(ячейки_стало)}"
    for i, (a, b) in enumerate(zip(ячейки_было, ячейки_стало, strict=True)):
        if a == b:
            continue
        try:
            if math.isclose(float(a), float(b), rel_tol=ДОПУСК, abs_tol=ДОПУСК):
                continue
        except ValueError:
            pass
        return f"{было.name}: ячейка {i} была {a!r}, стала {b!r}"
    return None


def _сравнить_файлы(было: Path, стало: Path) -> str | None:
    """Описание расхождения или None, если файлы считаются совпавшими.

    PNG не сравниваются вовсе: их вид зависит от версии matplotlib, и требовать
    побитового совпадения значило бы краснеть при обновлении рисовалки. Числа,
    по которым рисунок построен, лежат рядом в `panels.csv` и `facts.csv`,
    и сверяются они.
    """
    if not стало.exists():
        return f"{было.name}: пересчёт не создал файл"
    if было.suffix == ".png":
        return None
    if было.suffix == ".csv":
        return _сравнить_csv(было, стало)
    if было.read_text(encoding="utf-8") != стало.read_text(encoding="utf-8"):
        return f"{было.name}: текст разошёлся"
    return None


def сверить(
    метки: Sequence[str] = МЕТКИ_СВЕРКИ,
    корень: Path | None = None,
    этапы: Iterable[Этап] | None = None,
) -> list[str]:
    """Пересчитывает этапы и сравнивает выходы с тем, что лежало до пересчёта.

    Считается **на месте**, а выходы предварительно откладываются в сторону.
    Первая версия считала в копии дерева — и проверяла не то: пакет ставится
    в окружение как editable, поэтому запущенный в копии скрипт импортировал код
    исходного дерева, писал результат туда же и сравнивался сам с собой. Сверка
    проходила всегда, чего бы в копию ни положили.

    Возвращает список расхождений: пустой список означает, что репозиторий
    действительно производит то, что в нём лежит.
    """
    где = корень or PROJECT_ROOT
    выбранные = [э for э in (этапы or ЭТАПЫ) if э.метка in метки and э.выходы]
    расхождения: list[str] = []
    with tempfile.TemporaryDirectory() as врем:
        отложенные: dict[str, Path] = {}
        for э in выбранные:
            for относительный in э.выходы:
                исходный = где / относительный
                if not исходный.exists():
                    расхождения.append(f"{относительный}: в репозитории файла нет")
                    continue
                снимок = Path(врем) / относительный.replace("/", "__")
                shutil.copy2(исходный, снимок)
                отложенные[относительный] = снимок
        for э in выбранные:
            try:
                выполнить(э, где)
            except ReproduceError as ошибка:
                расхождения.append(str(ошибка))
                continue
            for относительный in э.выходы:
                снимок = отложенные.get(относительный)
                if снимок is None:
                    continue
                if беда := _сравнить_файлы(снимок, где / относительный):
                    расхождения.append(f"{э.имя}: {беда}")
        # Пересчёт, упавший на середине, оставил бы часть выходов от прошлого
        # запуска, а часть — от нового. Возвращаем отложенное только при расхождении.
        if расхождения:
            for относительный, снимок in отложенные.items():
                shutil.copy2(снимок, где / относительный)
    return расхождения
