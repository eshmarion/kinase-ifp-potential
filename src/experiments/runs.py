"""Папка прогона: состав, паспорт и защита от перезаписи.

Проверка состава живёт здесь, а не в скрипте выгрузки: тем же самым пользуется реестр
прогонов, а имена файлов не должны разъехаться между двумя местами.

**Полнота выгрузки и существование прогона — разные вопросы, и 18.09 они разведены.**
Выгрузка из облака без `molecules.sdf` неполна: файл там был, и раз он не доехал, значит
что-то оборвалось. А вот прогон, у которого молекул нет **в репозитории**, — законный
случай: они весят 85 % каталога, и класть в git молекулы каждого ночного прогона
не нужно. Прежде оба случая сводились к одному списку, и реестр объявлял
такой прогон `failed`, то есть «эксперимента не было».
"""

from __future__ import annotations

import hashlib
import json
import platform
from importlib import metadata
from pathlib import Path
from typing import Any, Final

from experiments.layout import MOLECULES_SDF, RUN_JSON

# Без чего **выгрузка** неполна. `failures.csv` сюда не входит намеренно: пустой список
# отказов — законный случай. Молекулы входят: в томе Modal они есть всегда, и если файл
# не доехал, выгрузка оборвалась.
REQUIRED_RUN_FILES: Final[tuple[str, ...]] = (RUN_JSON, MOLECULES_SDF)

# Без чего прогона **не существует**. Только паспорт: он несёт `run_id`, источник и штамп
# мишени, то есть отвечает на вопрос «что это был за эксперимент». Молекулы отвечают
# на другой вопрос — «можно ли пересчитать числа здесь и сейчас», и отсутствие ответа
# на него не делает эксперимент несостоявшимся.
REQUIRED_FOR_EXISTENCE: Final[tuple[str, ...]] = (RUN_JSON,)

# Поля паспорта, без которых прогон нельзя ни отличить от другого, ни описать в тексте
# курсовой.
REQUIRED_PASSPORT_FIELDS: Final[tuple[str, ...]] = ("run_id", "source", "created_utc")

# Библиотеки, версия которых меняет сами числа прогона. Список закрыт и короток
# намеренно: `numpy` задаёт поток бутстрэпа (зерно фиксировано, но `default_rng`
# не обещает одинаковую последовательность между версиями), `rdkit` несёт таблицу
# `fpscores` синтетической доступности,
# `prolif` считает сам отпечаток, `scipy` — критерий Манна–Уитни. Полный список
# установленного сюда не пишется: его никто не читает, а разойтись он может на пакете,
# от которого ни одно число не зависит.
NUMERIC_LIBRARIES: Final[tuple[str, ...]] = ("numpy", "rdkit", "prolif", "scipy")


class RunError(RuntimeError):
    """Папка прогона не соответствует форматам папки прогона и паспорта прогона."""


def missing_files(run_dir: Path) -> list[str]:
    """Имена файлов, без которых выгрузка неполна, — те, которых в папке нет.

    Отвечает на вопрос выгрузки, а не реестра: существование прогона проверяет
    `exists`, и молекул оно не требует.
    """
    return [имя for имя in REQUIRED_RUN_FILES if not (run_dir / имя).is_file()]


def exists(run_dir: Path) -> bool:
    """Есть ли у папки паспорт, то есть считается ли она прогоном вообще."""
    return all((run_dir / имя).is_file() for имя in REQUIRED_FOR_EXISTENCE)


def has_molecules(run_dir: Path) -> bool:
    """Лежит ли файл молекул рядом с паспортом.

    Отрицательный ответ означает «молекулы остались у автора и в томе Modal»,
    а не «прогон испорчен»: пересчитать по нему скор и метрики нельзя, но паспорт,
    метрики и ранжирование на месте и читаются.
    """
    return (run_dir / MOLECULES_SDF).is_file()


def read_passport(run_dir: Path) -> dict[str, Any]:
    """Читает `run.json` и проверяет обязательные поля.

    Поднимает `RunError`, если паспорта нет или он неполон: прогон без паспорта
    считается несуществующим и в таблицы не идёт.
    """
    путь = run_dir / RUN_JSON
    if not путь.is_file():
        raise RunError(f"В {run_dir} нет {RUN_JSON}: прогон без паспорта не существует")

    паспорт: dict[str, Any] = json.loads(путь.read_text(encoding="utf-8"))
    пустые = [поле for поле in REQUIRED_PASSPORT_FIELDS if not паспорт.get(поле)]
    if пустые:
        raise RunError(f"В {путь} не заполнены поля: {', '.join(пустые)}")
    return паспорт


def ensure_absent(run_dir: Path) -> None:
    """Отказывается работать, если папка прогона существует **и не пуста**.

    Перезапись прогона запрещена: восстановить затёртый результат нельзя,
    а новый запуск обязан получить новую подпапку.

    **Пустая папка результатом не является и отказа не вызывает** — 18.09 граница
    приведена к той же, что у `run_io.create_run_dir` и у проверки имени в сэмплере
    (одно правило, три реализации, и эта отставала). Пустую папку
    оставляет неудачная выгрузка: прогон в томе ещё не дописан, файлы не пришли, а каталог
    уже создан. При прежней границе повтор выгрузки был закрыт навсегда, потому что
    удалять в `runs/` нельзя, и разбирать приходилось руками. Запрет №2
    защищает молекулы и историю прогона, а не само имя каталога.
    """
    if run_dir.exists() and any(run_dir.iterdir()):
        raise RunError(
            f"Прогон уже выгружен: {run_dir} существует и не пуст. Перезапись запрещена — "
            "удалять или перезаписывать папки в runs/ нельзя, новый запуск даёт новый run_id"
        )


def check_pulled(run_dir: Path) -> dict[str, Any]:
    """Проверяет выгруженную папку целиком и возвращает её паспорт."""
    отсутствуют = missing_files(run_dir)
    if отсутствуют:
        raise RunError(
            f"Выгрузка неполна: в {run_dir} нет {', '.join(отсутствуют)}. "
            "Файл на месте только тогда, когда его видно на диске, а не в облаке"
        )
    return read_passport(run_dir)


def target_for_run(run_dir: Path, targets_dir: Path) -> Path:
    """Пакет мишени, к которой относится прогон.

    Мишень берётся из паспорта (`target.pdb_id`), а не из имени папки: имя собирается
    `make_run_id` и суффиксами и разбирается позиционно, поэтому любое изменение схемы
    имени молча уводит расчёт на чужую мишень. В паспорте же это отдельное поле,
    записанное производителем прогона.
    """
    паспорт = read_passport(run_dir)
    pdb_id = паспорт.get("target", {}).get("pdb_id")
    if not pdb_id:
        raise RunError(
            f"В паспорте {run_dir / RUN_JSON} не заполнено target.pdb_id — "
            "без него неизвестно, к какой мишени относится прогон (формат паспорта прогона)"
        )
    return targets_dir / str(pdb_id) / "target.json"


# Файлы пакета мишени, влияющие на отпечаток: по ним считается общий хэш пакета.
# Порядок фиксирован — иначе хэш зависел бы от порядка обхода каталога.
TARGET_PACKAGE_FILES: Final[tuple[str, ...]] = (
    "target.json",
    "protein.pdb",
    "protein_noh.pdb",
    "pocket.pdb",
    "ligand.sdf",
)


def record_condition(run_dir: Path, condition: str) -> dict[str, Any]:
    """Помечает прогон условием эксперимента и возвращает обновлённый паспорт.

    Условие живёт в паспорте, а оттуда попадает в каждую строку
    `metrics_per_molecule.csv` и в колонку `condition` реестра.
    Сравнение условий читает именно эту колонку, и пока условия не названы, она
    непроверяема — какие имена планируются, заранее неизвестно, поэтому
    умолчания у ключа нет: не пометил — значит не пометил.

    Дописать ключ в паспорт можно: неизменяемость защищает молекулы
    и историю прогона от перезаписи, а не мешает записать, чем прогон считали.
    Так же в паспорт дописывают `scoring` (`ensure_target_matches`), `ranking`
    (`ranking._record_selection`) и `main_line` (`record_main_line`).

    **Смена уже записанного условия — ошибка.** Прогон, помеченный одним условием
    и перемеченный другим, делает несравнимыми числа, которые из него уже
    процитированы: строка реестра меняется, а сославшийся на неё текст — нет.
    Повторная запись того же значения проходит молча, иначе цепочку прогона нельзя
    было бы запустить дважды.
    """
    условие = condition.strip()
    if not условие:
        raise RunError(f"{run_dir.name}: пустое условие эксперимента записывать нечем")

    паспорт_путь = run_dir / RUN_JSON
    паспорт = read_passport(run_dir)
    записанное = str(паспорт.get("condition", "")).strip()
    if записанное and записанное != условие:
        raise RunError(
            f"Прогон {run_dir.name} уже помечен условием {записанное!r}, "
            f"а его помечают как {условие!r}. Условие прогона не переписывается: "
            "числа из него могли попасть в текст. Нужен новый прогон, а не новая метка"
        )

    паспорт["condition"] = условие
    паспорт_путь.write_text(json.dumps(паспорт, indent=2, ensure_ascii=False), encoding="utf-8")
    return паспорт


def record_main_line(run_dir: Path, main_line: bool = True) -> dict[str, Any]:
    """Помечает прогон как представляющий работу и возвращает обновлённый паспорт.

    Принимает папку прогона и значение метки; пишет в паспорт ключ `main_line`.
    Читает её `registry.main_line_runs`: помеченный прогон представляет свой источник
    в таблице «было/стало» независимо от полноты и свежести.

    **Зачем метка, если правило и так выбирает само.** Решение №27 пересчитывает выбор
    при каждом запуске, и 18.09 это сработало неожиданно: прогон, поставленный ради
    сужения доверительных интервалов (293 молекулы против 95), молча стал главной
    линией вместо того, по которому написан раздел «Результаты».
    Метка разводит два разных вопроса: «какой прогон полнее» — вопрос к данным,
    «каким прогоном представлена работа» — решение авторов.

    Метка ничего не меняет, пока её никто не поставил: без неё правило работает
    по-прежнему. Ставить ли её и на каком прогоне — решение автора, а не
    механизма. Снять метку можно тем же вызовом с `main_line=False`: в отличие
    от условия эксперимента (`record_condition`), она не описывает, чем прогон считали,
    и её смена не делает несравнимыми уже процитированные числа.
    """
    паспорт_путь = run_dir / RUN_JSON
    паспорт = read_passport(run_dir)
    if main_line:
        паспорт["main_line"] = True
    else:
        паспорт.pop("main_line", None)
    паспорт_путь.write_text(json.dumps(паспорт, indent=2, ensure_ascii=False), encoding="utf-8")
    return паспорт


def library_versions() -> dict[str, str]:
    """Версии Python и библиотек, от которых зависят числа прогона.

    Отсутствующий пакет пропускается, а не пишется пустым значением: в образе
    генерации DiffSBDD нет ни `prolif`, ни `scipy`, и запись «prolif: null» читалась бы
    как «определить не смогли», хотя его там нет и быть не должно.
    """
    версии = {"python": platform.python_version()}
    for имя in NUMERIC_LIBRARIES:
        try:
            версии[имя] = metadata.version(имя)
        except metadata.PackageNotFoundError:
            continue
    return версии


def record_environment(run_dir: Path) -> dict[str, Any]:
    """Записывает в паспорт версии, которыми считаны числа прогона.

    Зерно бутстрэпа фиксировано, но одинаковый
    поток чисел между версиями `numpy` не обещан, а поля о версиях в паспорте не было
    вовсе — то есть фраза «пересчёт даёт те же границы» верна только внутри одного
    образа, и проверить это было нечем.

    Прогонам, посчитанным до 16.09, версии задним числом не приписываются: чем их
    считали, никто не записал, а правдоподобная запись хуже пустого места. Поле
    появляется при первом же пересчёте — так же, как появился `scoring`.

    **Расхождение с записанным — ошибка, а не предупреждение.** Числа, посчитанные
    в двух разных окружениях, несравнимы ровно так же, как отпечатки двух режимов
    протонирования, и смешать их в одной таблице можно только молча.
    Повторный счёт в том же окружении проходит без шума.
    """
    текущее = library_versions()
    паспорт_путь = run_dir / RUN_JSON
    паспорт = read_passport(run_dir)
    записанное = паспорт.get("environment")
    if записанное == текущее:
        return паспорт
    if записанное:
        разошлись = sorted(
            имя
            for имя in set(записанное) | set(текущее)
            if записанное.get(имя) != текущее.get(имя)
        )
        подробности = ", ".join(
            f"{имя}: было {записанное.get(имя, 'нет')}, стало {текущее.get(имя, 'нет')}"
            for имя in разошлись
        )
        raise RunError(
            f"Прогон {run_dir.name} считали в другом окружении ({подробности}). "
            "Числа разных версий несравнимы: либо считайте в том же образе, "
            "либо произведите прогон заново"
        )

    паспорт["environment"] = текущее
    паспорт_путь.write_text(json.dumps(паспорт, indent=2, ensure_ascii=False), encoding="utf-8")
    return паспорт


def target_stamp(target_json: Path) -> dict[str, Any]:
    """Отпечаток пакета мишени для паспорта прогона.

    Кроме `pdb_id` несёт режим протонирования и общий хэш файлов пакета. Без этого
    без штампа расчёт на втором ноутбуке давал несравнимые числа и молчал об этом:
    там пакет стоял в режиме `implicit-prolif`, а не `explicit`, и измерение
    прямо говорит, что отпечатки разных режимов между собой несравнимы.

    Хэш берётся по файлам, влияющим на отпечаток, а не по одному `target.json`:
    структура белка может смениться без правки паспорта мишени.
    """
    if not target_json.is_file():
        raise RunError(f"Пакет мишени не найден: {target_json}")

    package: dict[str, Any] = json.loads(target_json.read_text(encoding="utf-8"))
    дайджест = hashlib.sha256()
    for имя in TARGET_PACKAGE_FILES:
        путь = target_json.parent / имя
        if not путь.is_file():
            raise RunError(
                f"В пакете мишени {target_json.parent} нет {имя}: хэш пакета неполон, "
                "а неполный хэш хуже отсутствующего — он выглядит как совпадение"
            )
        дайджест.update(путь.read_bytes())

    return {
        "pdb_id": package.get("pdb_id"),
        "klifs_structure_id": package.get("klifs_structure_id"),
        "protonation": package.get("protonation"),
        "package_sha256": дайджест.hexdigest(),
    }


def compare_target_stamp(passport: dict[str, Any], target_json: Path) -> tuple[str, dict[str, Any]]:
    """Сверяет пакет мишени на диске с тем, на котором прогон произведён.

    Возвращает пару «вердикт, штамп пакета на диске». Вердикт:

    * `match` — штампы совпали;
    * `mismatch` — разошлись, считать нельзя;
    * `unstamped` — в паспорте штампа нет вовсе. Так выглядят прогоны, сделанные
      до появления этого поля; это не ошибка, но и не совпадение, и молчать о нём нельзя.
    """
    свежий = target_stamp(target_json)
    записанный = passport.get("target", {})
    if not записанный.get("package_sha256"):
        return "unstamped", свежий
    if записанный.get("package_sha256") != свежий["package_sha256"]:
        return "mismatch", свежий
    return "match", свежий


def stamp_target(run_dir: Path, target_json: Path) -> dict[str, Any]:
    """Проставляет штамп пакета мишени прогону, сделанному до формата паспорта прогона.

    Возвращает обновлённый паспорт. Нужна для прогонов от 23–24.08: штамп
    (`target.protonation` и `target.package_sha256`) появился 24.08 вечером, и три
    прогона старше его — `compare_target_stamp` отвечает по ним `unstamped`.
    Такой прогон расчёт принимает, но в тексте курсовой он выглядит слабее
    остальных: про него нельзя сказать, на каком пакете он посчитан.

    **Штамп — утверждение задним числом, и функция его не доказывает.** Основание
    может быть только одно: пересчёт прогона на этом пакете даёт те же числа.
    Для трёх прогонов 25.08 это измерено — `metrics_per_molecule.csv` и `ranking.csv`
    совпали посимвольно. Ставить штамп прогону, для которого такой
    сверки не делали, значит записать в паспорт непроверенное.

    Прогон, у которого штамп уже есть и совпадает, проходит молча; расхождение —
    ошибка: подменять чужой штамп своим нельзя ни при каких обстоятельствах.
    """
    вердикт, свежий = compare_target_stamp(read_passport(run_dir), target_json)
    if вердикт == "mismatch":
        raise RunError(
            f"Прогон {run_dir.name} несёт штамп другого пакета мишени. Штамп не "
            "переписывается: он говорит, на чём прогон посчитан, а не на чём его "
            "хотят видеть посчитанным"
        )

    паспорт_путь = run_dir / RUN_JSON
    паспорт: dict[str, Any] = json.loads(паспорт_путь.read_text(encoding="utf-8"))
    if вердикт == "match":
        return паспорт

    паспорт.setdefault("target", {}).update(
        protonation=свежий["protonation"],
        package_sha256=свежий["package_sha256"],
    )
    паспорт_путь.write_text(json.dumps(паспорт, indent=2, ensure_ascii=False), encoding="utf-8")
    return паспорт


def ensure_target_matches(run_dir: Path, target_json: Path) -> None:
    """Сверяет пакет мишени на диске с тем, на котором прогон произведён.

    Отпечатки, посчитанные при разных режимах протонирования, между собой несравнимы
, и 24.08 это стоило дня: пакет на одной машине стоял в `explicit`,
    на другой в `implicit-prolif`, а числа спокойно попали в таблицу как сопоставимые.
    Поэтому расхождение — `RunError`, а не предупреждение.

    Прогон, сделанный до появления штампа, не отвергается: считать по нему можно,
    но пакет, которым считали, записывается в паспорт отдельным ключом `scoring`.
    Дописать его в `target` было бы враньём — на каком пакете прогон произведён,
    неизвестно.

    Живёт здесь, а не в `ranking.py`, потому что сверка нужна каждому этапу, который
    считает отпечаток по чужому прогону: и скору, и целевым метрикам.
    """
    вердикт, свежий = compare_target_stamp(read_passport(run_dir), target_json)
    if вердикт == "match":
        # Версии пишутся здесь, а не при генерации: числа прогона рождаются на этапе
        # расчёта, и записать нужно то окружение, в котором их посчитали.
        record_environment(run_dir)
        return

    if вердикт == "mismatch":
        записанный = read_passport(run_dir)["target"]
        raise RunError(
            f"Прогон {run_dir.name} произведён на другом пакете мишени: "
            f"режим {записанный.get('protonation')!r}, хэш "
            f"{str(записанный.get('package_sha256'))[:12]}; на диске — "
            f"{свежий['protonation']!r}, хэш {свежий['package_sha256'][:12]}. "
            "Отпечатки разных режимов несравнимы: либо возьмите тот пакет, "
            "либо произведите прогон заново"
        )

    паспорт_путь = run_dir / RUN_JSON
    паспорт = json.loads(паспорт_путь.read_text(encoding="utf-8"))
    паспорт["scoring"] = {
        "protonation": свежий["protonation"],
        "package_sha256": свежий["package_sha256"],
    }
    паспорт_путь.write_text(json.dumps(паспорт, indent=2, ensure_ascii=False), encoding="utf-8")
    record_environment(run_dir)
    print(
        f"внимание: в паспорте {run_dir.name} нет штампа пакета мишени — прогон сделан "
        f"до появления штампа. Пакет расчёта записан в run.json: режим {свежий['protonation']!r}"
    )
