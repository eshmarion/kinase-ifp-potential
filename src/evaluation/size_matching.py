"""Подбор пар молекул одинакового размера.

Зачем модуль нужен. Отбор верхней доли по скору смещён в сторону крупных молекул:
медиана числа тяжёлых атомов растёт с 24 до 26 и с 22 до 27. Пока сравниваются две
группы разного размера, любое их различие можно объяснить размером, а не скором —
и это первое возражение, которое получит подраздел об отборе.

Способ снять возражение, не переставая пользоваться измеренными данными: сравнивать
не группы целиком, а пары «молекула из топа — отбракованная молекула того же размера».
Если преимущество держится внутри таких пар, размером оно не объясняется.

Подбор жадный и без возврата: пары строятся по возрастанию размера, каждая
отбракованная молекула используется не больше одного раза. Молекула топа, которой пары
не нашлось, из сравнения выпадает, и её потеря обязана быть видна в отчёте — иначе
сравнение незаметно перейдёт на подвыборку, о которой читатель не знает.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

# Насколько может различаться размер внутри пары. Единица, а не ноль: при нулевом
# допуске отсеивается больше половины топа, и сравнение теряет смысл вместе с мощностью.
DEFAULT_TOLERANCE: int = 1


@dataclass(frozen=True)
class SizedItem:
    """Молекула с размером и значением сравниваемой величины."""

    mol_id: str
    size: int
    value: float


@dataclass(frozen=True)
class Matching:
    """Построенные пары и то, сколько молекул в них не вошло."""

    pairs: list[tuple[SizedItem, SizedItem]]
    unmatched: int

    @property
    def differences(self) -> list[float]:
        """Разности «топ минус пара» по построенным парам."""
        return [верх.value - низ.value for верх, низ in self.pairs]


def match_by_size(
    selected: Sequence[SizedItem],
    rejected: Sequence[SizedItem],
    tolerance: int = DEFAULT_TOLERANCE,
) -> Matching:
    """Строит пары «отобранная молекула — отбракованная того же размера».

    Принимает две группы и допустимую разницу размеров; возвращает пары и число
    отобранных молекул, оставшихся без пары. Из подходящих кандидатов берётся ближайший
    по размеру, а при равенстве — первый по идентификатору: подбор обязан не зависеть
    от порядка строк в файле, иначе числа поедут при пересортировке таблицы.
    """
    if tolerance < 0:
        raise ValueError(f"допуск не может быть отрицательным: {tolerance}")

    свободные = sorted(rejected, key=lambda м: (м.size, м.mol_id))
    занятые: set[str] = set()
    пары: list[tuple[SizedItem, SizedItem]] = []
    for верх in sorted(selected, key=lambda м: (м.size, м.mol_id)):
        кандидаты = [
            м
            for м in свободные
            if м.mol_id not in занятые and abs(м.size - верх.size) <= tolerance
        ]
        if not кандидаты:
            continue
        пара = min(кандидаты, key=lambda м: (abs(м.size - верх.size), м.mol_id))
        занятые.add(пара.mol_id)
        пары.append((верх, пара))
    return Matching(pairs=пары, unmatched=len(selected) - len(пары))
