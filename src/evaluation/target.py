"""Целевые метрики прогона: сходство с эталоном и ключевые водородные связи.

Здесь только арифметика над отпечатками: ни RDKit, ни ProLIF, ни путей к папкам.
Отпечатки производит `kinase_ifp.fingerprint.compute_ifp`, обход прогона —
`experiments.metrics`.

**Чем эти метрики отличаются от скора.** Сходства считаются по всем семи типам
KLIFS, включая `HYD`: они сопоставляются с эталонным отпечатком KLIFS, где гидрофобные
контакты присутствуют, и выбрасывать их значило бы сравнивать разное. Скор `ifp_score`
берёт `SCORING_INTERACTION_TYPES` — все типы, кроме `HYD`.
Два числа про одну молекулу поэтому и не обязаны совпадать.
"""

from __future__ import annotations

from collections.abc import Sequence

import numpy as np

from kinase_ifp.config import HBOND_TYPES, KLIFS_INTERACTION_TYPES, N_KLIFS_POSITIONS
from kinase_ifp.similarity import as_full_ifp, tanimoto, tversky


def ifp_tanimoto(ifp: np.ndarray, reference: np.ndarray) -> float:
    """Коэффициент Танимото отпечатка молекулы и эталона по всем семи типам KLIFS.

    Принимает два массива формы (7, 85), возвращает число от 0 до 1. Мера симметрична,
    поэтому порядок аргументов на результат не влияет — в отличие от `ifp_tversky`.
    """
    return tanimoto(ifp, reference)


def ifp_tversky(ifp: np.ndarray, reference: np.ndarray) -> float:
    """Доля взаимодействий эталона, воспроизведённых молекулой (`alpha=1, beta=0`).

    Принимает два массива формы (7, 85), возвращает число от 0 до 1. Внутри эталон
    подставляется первым аргументом `tversky`: `alpha` штрафует биты именно первого
    массива, и «доля взаимодействий эталона» получается только при таком порядке.
    Обратный порядок дал бы долю битов молекулы — правдоподобное число, отвечающее
    на другой вопрос.
    """
    return tversky(reference, ifp, alpha=1.0, beta=0.0)


def key_hbond_positions(reference: np.ndarray) -> tuple[int, ...]:
    """Позиции KLIFS (1..85), на которых у эталонного лиганда есть водородная связь.

    Принимает эталонный отпечаток формы (7, 85), возвращает возрастающий кортеж номеров
    позиций, где стоит `DON` или `ACC`.

    Список считается из эталона, а не берётся из `HINGE_POSITIONS`, и это измеренное
    решение, а не упрощение. У кристаллического лиганда мишени 6tgu водородных связей
    с шарниром (46, 47, 48) нет вовсе: они приходятся на позиции 17 (каталитический
    лизин LYS69) и 81 (DFG-аспартат ASP176), а карман лиганд держит гидрофобно.
    Метрика по `HINGE_POSITIONS` давала бы 0 на кристаллическом лиганде — на верхней
    планке сравнения (`docs/metrics.md`, 3.2) — и мерила бы похожесть на типичный
    киназный ингибитор вместо близости к эталону этой мишени.

    Пустой кортеж — законный ответ: он означает эталон без единой H-связи в кармане,
    и решение, что делать дальше, принимает вызывающий код, а не эта функция.
    """
    bits = as_full_ifp(reference, "эталон")
    строки = [KLIFS_INTERACTION_TYPES.index(тип) for тип in HBOND_TYPES]
    есть_связь = bits[строки].any(axis=0)
    return tuple(int(индекс) + 1 for индекс in np.flatnonzero(есть_связь))


def hinge_hbond(ifp: np.ndarray, positions: Sequence[int]) -> int:
    """1, если у молекулы есть водородная связь хотя бы с одной из позиций; иначе 0.

    Позиции задаются номерами 1..85 и приходят аргументом, а не берутся из конфигурации:
    у метрик это ключевые позиции эталона (`key_hbond_positions`), у разметки — участок
    шарнира `HINGE_POSITIONS`, и обе задачи считают одну и ту же величину по разным
    спискам.

    Имя метрики историческое: колонка `hinge_hbond` зафиксирована заголовком
    таблицы метрик, и переименование сломало бы код, который его читает.

    Поднимает `ValueError` при пустом списке позиций или номере вне 1..85: молчаливый
    ноль в этом случае неотличим от честного «связи нет».
    """
    bits = as_full_ifp(ifp)
    if not positions:
        raise ValueError("Список ключевых позиций пуст: считать метрику не по чему")

    неверные = [позиция for позиция in positions if not 1 <= позиция <= N_KLIFS_POSITIONS]
    if неверные:
        raise ValueError(
            f"Позиции {неверные} вне диапазона 1..{N_KLIFS_POSITIONS}: "
            "нумерация KLIFS начинается с единицы"
        )

    строки = [KLIFS_INTERACTION_TYPES.index(тип) for тип in HBOND_TYPES]
    столбцы = [позиция - 1 for позиция in positions]
    return int(bits[np.ix_(строки, столбцы)].any())
