"""Парные критерии и поправка на множественность.

Зачем модуль нужен отдельно от `evaluation.stats`. Тот считает критерии для
**независимых** выборок: Манна–Уитни для топа против отбракованных, Спирмена для связи
двух рядов. В работе появились величины другого устройства — измеренные дважды на одних
и тех же молекулах. Доля молекул с ключевой водородной связью двоична и парна, и для неё
критерий один: Макнемара, который смотрит только на **несогласованные** пары, то есть
на молекулы, у которых связь появилась или исчезла. Согласованные пары о различии
не говорят ничего, и включать их в расчёт — значит разбавлять сигнал.

Точный биномиальный критерий, а не приближение хи-квадрат: несогласованных пар у нас
бывает меньше десятка, и приближение на таких числах врёт в сторону завышенной
значимости. Одна и та же величина обслуживает два критерия — Макнемара для двоичной
величины и знаковый для разности непрерывных, — потому что оба спрашивают у данных одно:
насколько неправдоподобно, что изменения в плюс и в минус равновероятны.

Поправка Холма, а не Бонферрони: она равномерно сильнее при том же контроле вероятности
хотя бы одной ложной находки и защищается так же просто. Бонферрони — её крайний
случай, поэтому переход ничего не ослабляет.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from math import comb, fsum

import numpy as np

from evaluation.stats import StatsError, bootstrap_ci


def exact_binomial_p(успехов: int, испытаний: int) -> float:
    """Двустороннее p точного биномиального критерия при вероятности успеха 1/2.

    Принимает число успехов и число испытаний, возвращает p-value. Ноль испытаний —
    это отсутствие изменений вовсе, и честный ответ здесь 1.0, а не ошибка: критерий
    не нашёл различия, потому что различать нечего.
    """
    if испытаний < 0 or not 0 <= успехов <= испытаний:
        raise StatsError(f"неверная пара «успехов, испытаний»: {успехов}, {испытаний}")
    if испытаний == 0:
        return 1.0
    край = min(успехов, испытаний - успехов)
    хвост = fsum(comb(испытаний, i) for i in range(край + 1)) / 2**испытаний
    return float(min(1.0, 2 * хвост))


@dataclass(frozen=True)
class PairedBinary:
    """Двоичная величина, измеренная до и после на одних и тех же объектах."""

    n: int
    before: float
    after: float
    gained: int
    lost: int
    p_value: float
    ci: tuple[float, float]


def mcnemar(before: Sequence[int], after: Sequence[int]) -> PairedBinary:
    """Критерий Макнемара для двоичной величины плюс интервал на разность долей.

    Принимает два ряда нулей и единиц одинаковой длины, выстроенных по парам;
    возвращает доли до и после, число приобретений и потерь, точное p по несогласованным
    парам и бутстрэп-интервал на разность долей.

    Интервал считается перцентильным бутстрэпом по разностям, а не формулой Ньюкомба:
    бутстрэп уже применяется в работе к другим величинам, и одна процедура на весь текст
    надёжнее двух, одна из которых написана ради единственного числа.
    """
    до = np.asarray(before, dtype=int)
    после = np.asarray(after, dtype=int)
    if до.size != после.size:
        raise StatsError(f"ряды разной длины: {до.size} и {после.size} — пары не построить")
    if до.size == 0:
        raise StatsError("парный критерий по пустой выборке: сравнивать нечего")
    if not (np.isin(до, (0, 1)).all() and np.isin(после, (0, 1)).all()):
        raise StatsError("критерий Макнемара требует нулей и единиц")

    приобретено = int(((до == 0) & (после == 1)).sum())
    потеряно = int(((до == 1) & (после == 0)).sum())
    разности = (после - до).astype(float)
    return PairedBinary(
        n=int(до.size),
        before=float(до.mean()),
        after=float(после.mean()),
        gained=приобретено,
        lost=потеряно,
        p_value=exact_binomial_p(приобретено, приобретено + потеряно),
        ci=bootstrap_ci(разности, aggregate="mean"),
    )


def sign_test(differences: Sequence[float]) -> tuple[int, int, float]:
    """Знаковый критерий для разностей: сколько в плюс, сколько в минус, какое p.

    Принимает разности по парам, возвращает число положительных, число отрицательных
    и точное двустороннее p. Нулевые разности отбрасываются — у них нет знака, и это
    то же правило, по которому Макнемара отбрасывает согласованные пары.

    Знаковый, а не Уилкоксона: величины у нас с массовыми связками (жёсткий скор
    принимает немного значений), и ранжирование разностей на таких данных опирается
    на порядок, которого в них нет.
    """
    значения = np.asarray(differences, dtype=float)
    if значения.size == 0:
        raise StatsError("знаковый критерий по пустой выборке: сравнивать нечего")
    плюс = int((значения > 0).sum())
    минус = int((значения < 0).sum())
    return плюс, минус, exact_binomial_p(плюс, плюс + минус)


def holm(p_values: Mapping[str, float]) -> dict[str, float]:
    """Поправка Холма на множественность внутри одного семейства критериев.

    Принимает отображение «имя теста → сырое p», возвращает то же отображение
    со скорректированными значениями. Порядок ключей сохраняется исходный, чтобы
    таблица в тексте не переставлялась сама.

    Монотонность обеспечивается накопительным максимумом: скорректированное значение
    не может оказаться меньше, чем у более значимого теста, иначе таблица противоречила
    бы сама себе.
    """
    if not p_values:
        raise StatsError("поправка по пустому семейству: корректировать нечего")
    if any(not 0.0 <= значение <= 1.0 for значение in p_values.values()):
        raise StatsError("p-value вне отрезка [0, 1]")

    по_возрастанию = sorted(p_values.items(), key=lambda пара: пара[1])
    всего = len(по_возрастанию)
    накопленный = 0.0
    исправленные: dict[str, float] = {}
    for номер, (имя, значение) in enumerate(по_возрастанию):
        накопленный = max(накопленный, min(1.0, (всего - номер) * значение))
        исправленные[имя] = накопленный
    return {имя: исправленные[имя] for имя in p_values}
