"""Альтернативные положения атомов в кристалле: расхождение и заселённости.

Зачем модуль нужен. Решение №16 выбирает из альтернативных моделей первую по алфавиту
(A) и обосновывает это тем, что KLIFS не отдаёт долей заселённости. Значимость выбора
обоснована числом — «у 6tgu боковая цепь HIS161 между моделями A и B разворачивается
на 6.95 Å», — и это число до 19.09 не воспроизводилось ничем: его посчитали 14.09
вручную по скачанному файлу PDB, а способ расчёта нигде не записали.

Что здесь считается. Группа альтернатив — это остаток, у части атомов которого стоит
метка `altLoc`. Расхождение группы — **наибольшее расстояние между одноимёнными
атомами** двух конформеров: оно отвечает на вопрос «насколько далеко уезжает самая
подвижная часть остатка», а не «насколько сместился остаток в среднем». Центроид
на том же HIS161 даёт 2.64 Å вместо 6.97 и утверждения «разворачивается целиком»
не подтверждает — притом что оба числа верны, просто отвечают на разные вопросы.

Водороды из расчёта **не исключаются**. Они есть в записи PDB, они часть конформера,
и наибольшее расхождение HIS161 приходится как раз на HE1. По одним тяжёлым атомам
выходит 5.71 Å — тоже осмысленное число, но другое, и выбор между ними надо делать
явно, а не умолчанием.

Заселённости нужны затем, что правило «берём A» и правило «берём мажорный конформер»
совпадают не всегда: на 6tgu они расходятся в 14 группах из 24, включая сам лиганд.
Это измерение стоит за наблюдением о расхождении моделей.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Final

# Колонки записи PDB, из которых читается альтернативное положение. Заданы форматом
# PDB, а не нами: имя атома 13–16, метка altLoc 17, заселённость 55–60.
ATOM_NAME: Final[slice] = slice(12, 16)
ALT_LOC: Final[slice] = slice(16, 17)
OCCUPANCY: Final[slice] = slice(54, 60)

# Минимальная длина строки, при которой координаты уже прочитаны полностью.
COORDS_END: Final[int] = 54


class AlternatesError(RuntimeError):
    """Запись PDB не даёт того, что нужно для разбора альтернатив."""


@dataclass(frozen=True)
class AlternateGroup:
    """Остаток с альтернативными положениями атомов."""

    resname: str
    chain: str
    resseq: str
    #: Метка конформера → его доля заселённости.
    occupancy: dict[str, float]
    #: Наибольшее расстояние между одноимёнными атомами A и B, ангстремы.
    shift: float
    #: Сколько пар одноимённых атомов участвовало в расчёте.
    pairs: int

    @property
    def label(self) -> str:
        """Как группа называется в отчётах: «HIS161»."""
        return f"{self.resname}{self.resseq}"

    @property
    def major(self) -> str:
        """Метка конформера с наибольшей заселённостью; при равенстве — первая по алфавиту."""
        return min(self.occupancy, key=lambda метка: (-self.occupancy[метка], метка))

    @property
    def first_is_major(self) -> bool:
        """Совпадает ли правило «берём A» с правилом «берём мажорный»."""
        return self.major == min(self.occupancy)


def read_alternates(text: str) -> list[AlternateGroup]:
    """Группы альтернативных положений из текста записи PDB.

    Принимает содержимое файла, возвращает по одной записи на остаток, у которого
    есть метка `altLoc`, отсортированные по убыванию расхождения. Читается первая
    модель: в записях ЯМР их десятки, и альтернативы там означают другое.

    Расхождение считается только между конформерами `A` и `B`: групп с третьим
    положением у наших структур нет, а правило «берём первую по алфавиту» сравнивает
    именно эти две. Если у группы нет ни одной пары одноимённых атомов в обоих
    конформерах, группа пропускается — расстояние там не определено.
    """
    координаты: dict[tuple[str, str, str], dict[str, dict[str, tuple[float, float, float]]]] = {}
    заселённость: dict[tuple[str, str, str], dict[str, float]] = {}

    for строка in text.splitlines():
        if строка.startswith("ENDMDL"):
            break
        if not строка.startswith(("ATOM", "HETATM")):
            continue
        if len(строка) < COORDS_END:
            raise AlternatesError(f"короткая запись PDB, координаты не читаются: {строка!r}")
        метка = строка[ALT_LOC].strip()
        if not метка:
            continue
        ключ = (строка[17:20].strip(), строка[21], строка[22:27].strip())
        имя = строка[ATOM_NAME].strip()
        точка = (float(строка[30:38]), float(строка[38:46]), float(строка[46:54]))
        координаты.setdefault(ключ, {}).setdefault(имя, {})[метка] = точка
        доля = строка[OCCUPANCY].strip()
        if доля:
            заселённость.setdefault(ключ, {})[метка] = float(доля)

    группы: list[AlternateGroup] = []
    for ключ, атомы in координаты.items():
        расстояния = [
            math.dist(положения["A"], положения["B"])
            for положения in атомы.values()
            if "A" in положения and "B" in положения
        ]
        if not расстояния:
            continue
        группы.append(
            AlternateGroup(
                resname=ключ[0],
                chain=ключ[1],
                resseq=ключ[2],
                occupancy=заселённость.get(ключ, {}),
                shift=max(расстояния),
                pairs=len(расстояния),
            )
        )
    return sorted(группы, key=lambda г: (-г.shift, г.label))
