# --------------------------------------------------------------------------------------
# KLIFS: канонический карман киназы
# --------------------------------------------------------------------------------------
# KLIFS выравнивает карман любой киназы на 85 канонических позиций, что и делает
# фингерпринт переносимым между разными киназами.

N_KLIFS_POSITIONS: Final[int] = 85
N_KLIFS_INTERACTION_TYPES: Final[int] = 7

# Официальный KLIFS IFP: 85 позиций × 7 типов. Строка из '0'/'1' такой длины приходит
# в колонке `interaction.fingerprint`.
KLIFS_IFP_LENGTH: Final[int] = N_KLIFS_POSITIONS * N_KLIFS_INTERACTION_TYPES  # 595

# Раскладка 595-битной строки KLIFS: (85 позиций, 7 типов), блоками по позициям.
#
# ИСПРАВЛЕНО 22.08.2026 по итогам измерения на 6tgu (CK2a2). Решение №11
# от 21.08.2026 утверждало обратный порядок — (7 типов, 85 позиций) — и было неверным.
#
# Проверка химическая, а не подгоночная. При раскладке (7, 85) эталонная строка 6tgu
# приписывает ароматические взаимодействия F-F позициям VAL66, LEU86, LEU89, THR93,
# а катионные ION- — глицину GLY47 и валину VAL113. У валина, лейцина, треонина и
# глицина нет ни ароматического кольца, ни заряженной группы: такие взаимодействия
# невозможны в принципе. При раскладке (85, 7) та же строка даёт согласованную картину:
# F-F у PHE114, F-E у HIS161, DON и ION+ у каталитического лизина LYS69, DON у DFG-
# аспартата ASP176 — и совпадает с нашим расчётом бит в бит (Танимото 0.59, ложных
# срабатываний ноль против 0.00 при прежней раскладке).
#
# Независимое подтверждение: разбор позиций по этой раскладке ставит каталитический
# лизин на позицию 17, и ровно её же даёт разметка KLIFS в решении №17, полученная
# совсем другим путём — по колонке `structure.pocket` на 7861 структуре.
#
# Первые 7 символов — все типы позиции 1, следующие 7 — позиции 2, и так далее.
# Разбор индекса i: позиция = i // N_KLIFS_INTERACTION_TYPES,
#                   тип      = i %  N_KLIFS_INTERACTION_TYPES.
KLIFS_BITS_SHAPE: Final[tuple[int, int]] = (N_KLIFS_POSITIONS, N_KLIFS_INTERACTION_TYPES)

# Форма массива, которым проект оперирует внутри: (7 типов, 85 позиций).
#
# Она намеренно транспонирована относительно KLIFS_BITS_SHAPE: скор и потенциал берут
# срез по типу взаимодействия (`ifp[DON]` — все позиции разом), и держать тип первой
# осью удобнее. Преобразование между двумя раскладками живёт в одном месте —
# `fingerprint.bits_to_ifp` и `fingerprint.ifp_to_bits`, — и нигде не повторяется.
KLIFS_IFP_SHAPE: Final[tuple[int, int]] = (N_KLIFS_INTERACTION_TYPES, N_KLIFS_POSITIONS)

# Порядок типов взаимодействий в 595-битной строке KLIFS.
KLIFS_INTERACTION_TYPES: Final[tuple[str, ...]] = (
    "HYD",   # гидрофобный контакт
    "F-F",   # ароматическое взаимодействие «плоскость к плоскости»
    "F-E",   # ароматическое взаимодействие «ребро к плоскости»
    "DON",   # белок — донор водородной связи
    "ACC",   # белок — акцептор водородной связи
    "ION+",  # катион белка — анион лиганда
    "ION-",  # анион белка — катион лиганда
)

# Типы, по которым считается скор: все, кроме HYD.
#
# Гидрофобный контакт доминирует в отпечатке численно и при этом ненаправлен: он возникает
# от простой близости атомов, поэтому смещённая поза набирает его случайно. Измерено
# 02.09.2026 (docs/metrics.md, 3.9): в эталонах KLIFS (7462 структуры, 227 киназ) медианная
# доля HYD 0.800 — 15 гидрофобных бит против 4 специфичных; на 11 киназах с позами известного
# качества исключение HYD поднимает медианный Спирмен скора с RMSD с -0.522 до -0.684
# и медианный AUC с 0.952 до 0.971, не проигрывая по AUC ни на одной киназе. Вред
# пропорционален доле HYD: там, где её меньше 60%, оба варианта дают одно и то же.
# Тот же выбор и по тому же основанию — Errington et al., J Cheminform 17:76 (2025).
# Механизм измерен 09.09.2026 (docs/calibration.md, 3): порог 4.5 A у нас и у KLIFS
# одинаков, различается отбор атомов. Правило KLIFS восстановлено перебором — углерод,
# сера или хлор остатка, остова наравне с боковой цепью, в пределах 4.5 A от углерода,
# серы или хлора лиганда: 16.09.2026 это дало 143 эталонных бита из 143 при нуле ложных
# (прежняя реконструкция «любой углерод» давала 139 из 143). То есть их HYD — признак
# близости, а не тип взаимодействия, и исключается величина, взаимодействием
# не являющаяся. Набор элементов — APOLAR_ATOM_ELEMENTS ниже.
# В эталонном отпечатке HYD при этом остаётся: без него сверка с KLIFS стала бы
# несопоставимой.
# Выводится из KLIFS_INTERACTION_TYPES, а не переписывается списком: добавленный когда-либо
# тип попадёт в скор автоматически, а не будет молча пропущен.
SCORING_INTERACTION_TYPES: Final[tuple[str, ...]] = tuple(
    t for t in KLIFS_INTERACTION_TYPES if t != "HYD"
)

# Типы KLIFS, означающие водородную связь.
#
# Имя типа описывает роль БЕЛКА: `DON` — белок донор (лиганд акцептор), `ACC` — наоборот.
# Там, где важен сам факт связи, а не её направление, берутся оба типа: так считает
