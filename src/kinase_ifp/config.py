# --------------------------------------------------------------------------------------
# Правила FingerPrintLib: воспроизведение эталонного отпечатка KLIFS
# --------------------------------------------------------------------------------------
# Источник — Marcou G., Rognan D. // J. Chem. Inf. Model. 2007. Vol. 47, № 1. P. 195–207,
# таблицы 2 (флаги атомов), 3 (порядок бит) и 4 (геометрия), ОСНОВНОЙ текст статьи.
# Этой же библиотекой KLIFS считает свои эталоны (van Linden et al., 2014).
#
# Всё, что ниже, — цитата, а не наш выбор. Наши собственные пороги живут в
# PROLIF_PARAMETERS и меняться под эти числа не должны: подгонка нашей химии под чужую
# геометрию запрещена решением №25. Эти константы обслуживают отдельный расчёт —
# «что дал бы их алгоритм», — а не наш отпечаток.
#
# Статья описывает восемь типов и одиннадцать бит; KLIFS берёт первые семь
# (KLIFS_INTERACTION_TYPES). Слабая водородная связь, π-катион и комплексация металла
# в эталон KLIFS не входят и здесь не заводятся.

# Таблица 2: флаг `hydrophobe` — SMARTS [C,S,F,Cl,Br,I]. Совпадает с APOLAR_ATOM_ELEMENTS,
# который был восстановлен перебором независимо.
KLIFS_RULE_HYDROPHOBE_ELEMENTS: Final[tuple[str, ...]] = APOLAR_ATOM_ELEMENTS

# Таблица 4: ||Y1Y2|| <= 4.5 A между двумя гидрофобными атомами.
KLIFS_RULE_HYDROPHOBE_DISTANCE: Final[float] = APOLAR_CONTACT_DISTANCE

# Таблица 4: ||DA|| < 3.5 A и угол между направлением связи D-H и направлением D->A
# меньше 45 градусов (в статье — интервал [-pi/4, pi/4]).
#
# ВАЖНО, ЧЕМ МЕРЯЕТСЯ УГОЛ. Это угол между связью D-H и вектором D->A, а НЕ между
# векторами D->H и H->A. Вторая величина примерно вдвое чувствительнее, и по ней те же
# комплексы требовали бы допуска 60 градусов вместо напечатанных 45. Так считает
