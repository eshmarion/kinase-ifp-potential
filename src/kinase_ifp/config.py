# М1, член стерического клэша. Образец - delta_SC в BInD (Lee et al., Adv Sci 2025,
# DOI 10.1002/advs.202502702): шарнирный штраф max(0, d_min - d_ij) по всем парам
# лиганд-белок, слагаемым в целевой функции, а не фильтром шага.
#
# Порог пары берётся как доля от суммы ван-дер-ваальсовых радиусов, а не одним числом
# для всех пар, как CLASH_DISTANCE_A: у пары C-C сумма радиусов 3.40 A, у пары C-H -
# 2.90 A, и общий порог 2.0 A для первой слишком мягок, для второй слишком строг.
# Значение 0.75 взято у PoseBusters (Buttenschoen et al., Chem Sci 2024) и калибровано
# его авторами так, что почти все кристаллические структуры порог проходят.
#
# **Важная оговорка о круге.** Физичность позы мы меряем тем же PoseBusters, поэтому
# улучшение его теста `minimum_distance_to_protein` у варианта М1 частично тавтологично:
# потенциал оптимизирует ровно ту величину, которой его потом проверяют. Независимой
# мерой для М1 остаётся энергия Vina, в которую этот порог не входит.
CLASH_VDW_FRACTION: Final[float] = 0.75

# Вес члена клэша в целевой функции М1: скор безразмерен и лежит в [0, 1], штраф
# считается в ангстремах суммарного нарушения по всем парам.
#
# Значение выбрано свипом 18.09.2026 на прогоне 2026-08-23-6tgu-s0-n100-prep по правилу,
# объявленному до расчёта: **наименьший вес, при котором физичность позы не хуже, чем
# у исходных молекул**. Правило нужно затем, чтобы вес не подбирался под желаемый
# результат: у него есть верхняя и нижняя границы по смыслу, и обе достигаются.
# Измерено (молекул с тяжёлым атомом ближе 2.55 A от белка, из 98):
#   исходные 29, вес 0.1 — 40, вес 0.5 — 27, вес 2.0 — 31.
# Прирост целевого скора при этом от веса почти не зависит (+0.086 / +0.083 / +0.082
# против +0.087 у варианта без члена клэша), то есть член клэша чинит физичность,
# не отнимая у потенциала его собственного эффекта.
CLASH_PENALTY_WEIGHT: Final[float] = 0.5

# М2, взвешивание бит по частоте. Образец - PADIF (Jasper et al., J Cheminform 2018,
# 10:15): биты взвешиваются частотой соответствующего взаимодействия среди множества
# эталонных структур, то есть консервативные точки связывания весят больше случайных.
#
# Направление взвешивания - прямое, как у PADIF: чем чаще бит встречается в базе, тем
# он важнее. Обратное (IDF, «редкое информативнее») здесь неуместно: в киназном кармане
# часто встречаются именно канонические контакты - H-связь с шарниром, контакт
# с каталитическим лизином, - и они и есть то, что потенциал должен воспроизводить.
#
# Сглаживание Лапласа: вес бита = (частота + eps) / (макс. частота + eps), eps = 1/N.
# Без него бит эталона, ни разу не встретившийся в базе, получил бы вес 0 и выпал
# из знаменателя - то есть перестал бы требоваться вовсе.
BIT_WEIGHT_SMOOTHING_COUNT: Final[float] = 1.0
