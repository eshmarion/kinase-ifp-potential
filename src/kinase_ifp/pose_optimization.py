"""Оптимизация позы лиганда дискретным потенциалом взаимодействий.

Зачем это нужно. `ifp_score` до сих пор только **сортировал** готовые молекулы: если
в наборе нет молекулы с нужной водородной связью, сортировка её не создаст. Здесь тот
же скор впервые работает как потенциал — величина, которую оптимизируют, двигая
молекулу, — и делает это без производной.

Почему без производной и почему это законно. Скор кусочно-постоянен: бит ставится
по порогу, поэтому как функция координат он ступенька, у которой градиент равен нулю
всюду, где определён. Ступенчатые потенциалы оптимизируют не спуском, а выборкой:
критерием Метрополиса, как контактные потенциалы типа модели Гō, или по событиям
на разрывах, как дискретная молекулярная динамика (`docs/sources.md`, раздел 1.1).
Здесь взят Метрополис: он не требует ни аналитической геометрии разрывов, ни
непрерывности энергии.

Что именно двигается. Молекула перемещается как **жёсткое тело** — поворот вокруг
своего центра тяжёлых атомов плюс сдвиг. Торсионные углы не меняются намеренно:
конформацию породила диффузионная модель, и её перебор был бы уже не оптимизацией
позы, а другой задачей. Смещение от исходной позы ограничено `max_rmsd`, иначе
оптимизация уводила бы молекулу в соседний карман, где скор случайно выше.

Физичность держится правилом контакта, и оно двустороннее: хорошая поза не пускается
ближе `CLASH_DISTANCE_A` к тяжёлым атомам кармана, а поза, пришедшая уже налезшей, не
делается хуже, чем пришла. Без такой проверки потенциал вида «больше контактов — лучше»
вжимает молекулу в белок, потому что контакты от этого растут. Второй половине правила
есть измеренная причина: у 84 молекул прогона из 100 тяжёлый атом стоит к карману ближе
2.0 Å (у кристаллического лиганда — 2.66 Å), и требование «наложения нет» запретило бы
им любое движение — то есть отказало бы ровно там, где исправлять нужнее всего.

Ничьи разрешаются метрикой, а не порядком: скор дискретен, равные значения — норма,
и выбор «первой попавшейся позы» означал бы отбор по номеру шага. Сравниваются тройки
«скор, минус смещение»: при равном скоре побеждает поза, которая сдвинулась меньше.

Какую именно величину оптимизировать, модуль больше не решает: целевая функция
приходит параметром `potential` и живёт в `kinase_ifp.potential` (варианты М0, М1, М2).
Без этого параметра берётся дискретный скор, то есть прежнее поведение.
Отчётный `score_*` при этом всегда считается базовой формулой независимо от варианта —
иначе варианты сравнивались бы значениями разных функций.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Final

import numpy as np
from rdkit import Chem

from kinase_ifp.config import SCORING_INTERACTION_TYPES
from kinase_ifp.fingerprint_klifs import PocketRules, ifp_from_groups
from kinase_ifp.ligand_flags import groups_from_mol
from kinase_ifp.mol2_reader import read_mol2
from kinase_ifp.poses import apply_rigid, heavy_atom_centroid, heavy_atom_rmsd, rotation_matrix
from kinase_ifp.potential import DiscretePotential, Potential

# Ближе этого расстояния тяжёлые атомы лиганда и белка считаются наложившимися.
# Меньше любой химической связи, поэтому отсекается именно наложение, а не тесный контакт.
CLASH_DISTANCE_A: Final[float] = 2.0

# Шаг предложения: сдвиг в ангстремах и поворот в градусах. Подобраны так, чтобы
# один шаг менял хотя бы одно взаимодействие, но не выбрасывал молекулу из кармана:
# порог водородной связи — 3.5 Å, ионного контакта — 4.0 Å.
STEP_SHIFT_A: Final[float] = 0.35
STEP_ROTATION_DEG: Final[float] = 8.0

# Температура критерия Метрополиса в единицах скора. Скор на 6tgu принимает шесть
# значений с шагом 0.2, поэтому 0.1 делает подъём на одну ступень маловероятным,
# но возможным: exp(-0.2/0.1) ≈ 0.14. Нулевая температура превратила бы поиск
# в жадный спуск и запирала бы молекулу в первом же локальном минимуме.
TEMPERATURE: Final[float] = 0.1

# Предел смещения позы от исходной. 1.5 Å - это порог, по которому в докинге позу
# считают воспроизведённой, поэтому в его пределах поза остаётся «той же самой»,
# а не подменяется другой. Величина при этом рабочая, а не священная: свип показал
# 0.520 / 0.724 / 0.880 по скору для 0.5 / 1.5 / 3.0 Å, и вопрос, что считать
# допустимым вмешательством, решается не здесь, а постановкой задачи.
MAX_RMSD_A: Final[float] = 1.5


class PoseOptimizationError(RuntimeError):
    """Оптимизировать позу нельзя: нет координат кармана или испорчен вход."""


@dataclass(frozen=True)
class OptimizationResult:
    """Итог оптимизации одной молекулы.

    `steps_accepted` и `steps_improved` разведены намеренно: принятый шаг может быть
    и ухудшением (критерий Метрополиса это допускает), а улучшений на плато скора
    не бывает вовсе — по их числу видно, двигался ли потенциал вообще.

    `min_distance_before` и `min_distance_after` — минимальное расстояние от тяжёлого
    атома лиганда до тяжёлого атома кармана. Они в итоге не ради полноты: у молекул
    прогона это расстояние в медиане 1.32 Å против 2.66 Å у кристаллического лиганда,
    то есть физичность позы измеряется, а не предполагается.
    """

    mol: Chem.Mol
    score_before: float
    score_after: float
    rmsd_shift: float
    steps_accepted: int
    steps_improved: int
    clashes_rejected: int
    min_distance_before: float
    min_distance_after: float
    # Значение целевой функции того варианта потенциала, которым шла оптимизация.
    # Разведено со `score_*` намеренно: `score_*` — всегда базовый дискретный скор
    # базовой формулы, по которой три варианта только и можно сравнивать между собой,
    # а `objective_*` — то, что вариант оптимизировал на самом деле. У варианта
    # `discrete` обе пары совпадают, у `clash` и `weighted` расходятся.
    objective_before: float = 0.0
    objective_after: float = 0.0
    potential_name: str = "discrete"


def pocket_heavy_atoms(package_json: Path) -> np.ndarray:
    """Координаты тяжёлых атомов кармана из `pocket.mol2` — массив (N, 3).

    Нужны только для проверки на налезание, поэтому флаги правил здесь не при чём:
    берутся все атомы, кроме водородов.
    """
    карман = package_json.parent / "pocket.mol2"
    if not карман.is_file():
        raise PoseOptimizationError(f"нет pocket.mol2 в пакете {package_json.parent}")
    структура = read_mol2(карман)
    точки = [атом.xyz for атом in структура.atoms if атом.element != "H"]
    if not точки:
        raise PoseOptimizationError(f"в {карман} нет тяжёлых атомов")
    return np.asarray(точки, dtype=float)


def pocket_vdw_radii(package_json: Path) -> np.ndarray:
    """Ван-дер-ваальсовы радиусы тяжёлых атомов кармана — массив (N,) в том же порядке.

    Нужны варианту потенциала М1: его порог зависит от пары элементов, а не одинаков
    для всех пар. Порядок атомов обязан совпадать с `pocket_heavy_atoms`, поэтому
    отбор здесь тот же — всё, кроме водорода, — и функции читают один и тот же файл.

    Радиусы берутся из таблицы RDKit, а не из своего списка: своя таблица была бы
    четвёртым местом в проекте, где записаны свойства элементов.
    """
    карман = package_json.parent / "pocket.mol2"
    if not карман.is_file():
        raise PoseOptimizationError(f"нет pocket.mol2 в пакете {package_json.parent}")
    таблица = Chem.GetPeriodicTable()
    структура = read_mol2(карман)
    радиусы = [
        таблица.GetRvdw(атом.element.capitalize())
        for атом in структура.atoms
        if атом.element != "H"
    ]
    if not радиусы:
        raise PoseOptimizationError(f"в {карман} нет тяжёлых атомов")
    return np.asarray(радиусы, dtype=float)


def _heavy_coords(mol: Chem.Mol) -> np.ndarray:
    conf = mol.GetConformer()
    return np.asarray(
        [
            [
                conf.GetAtomPosition(атом.GetIdx()).x,
                conf.GetAtomPosition(атом.GetIdx()).y,
                conf.GetAtomPosition(атом.GetIdx()).z,
            ]
            for атом in mol.GetAtoms()
            if атом.GetAtomicNum() != 1
        ],
        dtype=float,
    )


def min_pocket_distance(mol: Chem.Mol, pocket_atoms: np.ndarray) -> float:
    """Минимальное расстояние от тяжёлого атома лиганда до тяжёлого атома кармана."""
    лиганд = _heavy_coords(mol)
    расстояния = np.linalg.norm(лиганд[:, None, :] - pocket_atoms[None, :, :], axis=2)
    return float(расстояния.min())


def has_clash(mol: Chem.Mol, pocket_atoms: np.ndarray) -> bool:
    """Есть ли наложение тяжёлых атомов лиганда на тяжёлые атомы кармана."""
    return min_pocket_distance(mol, pocket_atoms) < CLASH_DISTANCE_A


def optimize_pose(
    mol: Chem.Mol,
    pocket: PocketRules,
    reference_ifp: np.ndarray,
    pocket_atoms: np.ndarray,
    *,
    steps: int = 300,
    max_rmsd: float = MAX_RMSD_A,
    seed: int = 0,
    temperature: float = TEMPERATURE,
    scoring_types: Sequence[str] = SCORING_INTERACTION_TYPES,
    potential: Potential | None = None,
) -> OptimizationResult:
    """Двигает молекулу как жёсткое тело, повышая значение потенциала по Метрополису.

    Принимает подготовленную молекулу (явные водороды, один конформер), разобранный
    карман, эталонный отпечаток, координаты тяжёлых атомов кармана; возвращает
    `OptimizationResult` с лучшей найденной позой.

    `potential` задаёт, какую величину оптимизировать (`kinase_ifp.potential`). Без него
    берётся дискретный скор, то есть поведение по умолчанию не изменилось.
    Независимо от варианта в `score_before` и `score_after` кладётся **базовый**
    дискретный скор: три варианта потенциала сравниваются между собой только по нему,
    иначе сравнивались бы значения разных функций.

    Шаг отвергается, если поза налезает на белок или уводит молекулу дальше
    `max_rmsd` от исходной. Возвращается **лучшая** поза за траекторию, а не
    последняя: критерий Метрополиса допускает ухудшающие шаги, и последняя поза
    может быть хуже найденного минимума.
    """
    if mol.GetNumConformers() == 0:
        raise PoseOptimizationError("у молекулы нет конформера")

    rng = np.random.default_rng(seed)
    исходная = Chem.Mol(mol)

    # Базовый скор по заданному набору типов: доля ключевых взаимодействий эталона,
    # воспроизведённых позой. Набор — параметр, а не константа, потому что состав
    # типов сам является предметом измерения: на верных правилах KLIFS включение
    # гидрофобных контактов поднимает разделительную способность и почти убирает
    # плато (12 различных значений скора против 6).
    базовый = DiscretePotential(reference_ifp=reference_ifp, scoring_types=scoring_types)
    цель: Potential = potential if potential is not None else базовый

    def отпечаток(молекула: Chem.Mol) -> np.ndarray:
        return ifp_from_groups(groups_from_mol(молекула), pocket)

    def скор(молекула: Chem.Mol) -> float:
        """Значение оптимизируемой величины — то, что двигает поиск."""
        return цель(молекула, отпечаток(молекула))

    def базовый_скор(молекула: Chem.Mol) -> float:
        """Дискретный скор — то, по чему варианты сравниваются."""
        return базовый(молекула, отпечаток(молекула))

    # Порог контакта, который шаг не имеет права ухудшить. У 84 молекул прогона из 100
    # тяжёлый атом стоит к белку ближе 2.0 Å (у кристаллического лиганда — 2.66 Å),
    # поэтому требование «нет наложения» отвергало бы у них **любой** шаг, и потенциал
    # не двигал бы ровно те позы, которые нужно исправлять. Правило поэтому иное:
    # хорошую позу не пускать за порог, плохую — не делать хуже, чем она пришла.
    дно = min(CLASH_DISTANCE_A, min_pocket_distance(mol, pocket_atoms))

    текущая = Chem.Mol(mol)
    текущий = скор(текущая)
    начальный = текущий

    # Ничьи разрешаются метрикой, а не порядком появления позы: скор дискретен,
    # равные значения — норма, и выбор «первой попавшейся» означал бы отбор
    # по номеру шага, то есть по случайной величине.
    #
    # Второй ключ — **меньшее** смещение от исходной позы, и только он. Пробовался
    # ключ «дальше от белка», и он оказался скрытой второй целью: на пустом эталоне,
    # где скор тождественно нулевой, молекула всё равно уезжала на 1.44 Å, отодвигаясь
    # от белка с 2.66 до 3.02 Å. Тогда рост физичности приписывался бы потенциалу,
    # хотя его создавал тайбрейк. Ключ «двигай меньше» такой цели не создаёт:
    # при равном скоре он оставляет позу на месте.
    лучшая = Chem.Mol(текущая)
    лучший = (текущий, 0.0)

    принято = улучшений = налезаний = 0
    for _ in range(steps):
        ось = rng.normal(size=3)
        ось /= np.linalg.norm(ось)
        сдвиг = rng.normal(size=3) * STEP_SHIFT_A
        поворот = rotation_matrix(ось, np.deg2rad(rng.normal() * STEP_ROTATION_DEG))
        проба = apply_rigid(текущая, поворот, сдвиг, heavy_atom_centroid(текущая))

        расстояние = min_pocket_distance(проба, pocket_atoms)
        if расстояние < дно:
            налезаний += 1
            continue
        смещение = heavy_atom_rmsd(проба, исходная)
        if смещение > max_rmsd:
            continue

        значение = скор(проба)
        разница = значение - текущий
        # Энергия — минус скор, поэтому подъём скора принимается всегда, а падение —
        # с вероятностью exp(-ΔE/T). Плато (разница 0) принимается: именно так поиск
        # проходит через группы поз с одинаковым скором, которых у дискретной
        # величины большинство.
        if разница >= 0 or rng.random() < float(np.exp(разница / temperature)):
            текущая, текущий = проба, значение
            принято += 1
            if разница > 0:
                улучшений += 1
            # Сравнение по трём метрикам сразу: скор, затем физичность контакта,
            # затем меньшее смещение (минус, потому что сравниваются «больше лучше»).
            претендент = (значение, -смещение)
            if претендент > лучший:
                лучшая, лучший = Chem.Mol(проба), претендент

    # Базовый скор считается отдельно и только дважды — для исходной и для лучшей позы.
    # Внутри цикла он не нужен: поиск ведёт `цель`, а базовый скор здесь нужен ради
    # сравнимости вариантов между собой, и лишний расчёт отпечатка на каждом из тысячи
    # шагов удвоил бы стоимость оптимизации ради двух чисел.
    return OptimizationResult(
        mol=лучшая,
        score_before=базовый_скор(исходная),
        score_after=базовый_скор(лучшая),
        rmsd_shift=heavy_atom_rmsd(лучшая, исходная),
        steps_accepted=принято,
        steps_improved=улучшений,
        clashes_rejected=налезаний,
        min_distance_before=min_pocket_distance(исходная, pocket_atoms),
        min_distance_after=min_pocket_distance(лучшая, pocket_atoms),
        objective_before=начальный,
        objective_after=лучший[0],
        potential_name=цель.name,
    )
