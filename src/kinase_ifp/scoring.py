"""IFP-скор и переранжирование молекул прогона.

Скор — доля ключевых взаимодействий эталона, воспроизведённых молекулой. Считается
по `SCORING_INTERACTION_TYPES`, то есть по всем типам, кроме гидрофобных: гидрофобный
контакт возникает почти у любой молекулы подходящего размера и заглушил бы шесть
специфичных типов. Метрики сходства `ifp_tanimoto` и `ifp_tversky`,
наоборот, считаются по всем семи — там важнее сопоставимость с эталоном KLIFS.

Лишние взаимодействия скор не штрафует: `tversky(эталон, молекула)` при `alpha=1,
beta=0` — это ровно `|общие| / |эталон|`. Решение осознанное: контакт, которого нет
у эталонного лиганда, сам по себе не дефект, а симметричная мера (Танимото) как
потенциал уровня B толкала бы модель к обеднённым молекулам.

Эта же функция на уровне B становится потенциалом, поэтому она отделена от кода
чтения прогонов и ни от чего, кроме двух отпечатков, не зависит.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any

import numpy as np

from kinase_ifp.config import SCORING_INTERACTION_TYPES
from kinase_ifp.similarity import select_types, tversky

# Доля прогона, попадающая в отобранный топ, если не задано иное. Значение из
# минимальной защищаемой версии: условие `rerank-top20`.
DEFAULT_TOP_FRACTION: float = 0.2


class ScoringError(RuntimeError):
    """Скор посчитать нельзя: нет эталона или испорчены входные данные."""


@dataclass(frozen=True)
class ScoredMolecule:
    """Строка `ranking.csv` до присвоения ранга (формат таблицы ранжирования)."""

    mol_id: str
    ifp_score: float
    ifp_score_norm: float


def ifp_score(ifp: np.ndarray, reference: np.ndarray) -> float:
    """Доля ключевых взаимодействий эталона, воспроизведённых молекулой.

    Принимает два отпечатка формы (7, 85), возвращает число от 0 до 1. Гидрофобные
    контакты в расчёт не входят. Если у эталона нет ни одного бита по типам скора,
    возвращает 0.0: воспроизводить нечего, и делить не на что.

    Порядок аргументов важен: эталон первым. `tversky` штрафует биты именно первого
    массива, поэтому «доля взаимодействий эталона» — это `tversky(эталон, молекула)`,
    а перепутанный порядок даёт другое число и ничего не сообщает.
    """
    эталон = select_types(reference, SCORING_INTERACTION_TYPES)
    молекула = select_types(ifp, SCORING_INTERACTION_TYPES)
    return tversky(эталон, молекула, alpha=1.0, beta=0.0)


def score_norm(score: float, n_heavy_atoms: int) -> float:
    """Скор, делённый на число тяжёлых атомов.

    Без внешней метрики это единственный ответ на
    претензию «вы просто отобрали молекулы покрупнее»: крупная молекула набирает
    больше контактов просто размером, и нормировка это учитывает — та же логика,
    что у ligand efficiency.

    Поднимает `ScoringError` при неположительном числе атомов: молекулы без тяжёлых
    атомов не бывает, и деление на ноль здесь означает испорченный вход.
    """
    if n_heavy_atoms <= 0:
        raise ScoringError(f"Число тяжёлых атомов {n_heavy_atoms}: молекула испорчена")
    return score / n_heavy_atoms


def rank_molecules(
    scored: list[ScoredMolecule], top_fraction: float = DEFAULT_TOP_FRACTION
) -> list[dict[str, Any]]:
    """Расставляет ранги и отмечает отобранный топ. Возвращает строки формата таблицы ранжирования.

    Ранг 1 — наибольший скор. Молекулы с одинаковым скором сохраняют порядок появления
    в прогоне: воспроизводимость таблицы важнее, чем разрешение ничьих по какому-либо
    второму признаку, который пришлось бы придумывать.

    `top_fraction` — доля прогона, попадающая в топ; размер округляется вверх, чтобы
    на маленьком наборе топ не оказался пустым.
    """
    if not 0.0 < top_fraction <= 1.0:
        raise ScoringError(f"Доля топа {top_fraction} вне диапазона (0, 1]")
    if not scored:
        raise ScoringError("Пустой список молекул: ранжировать нечего")

    порядок = sorted(range(len(scored)), key=lambda i: (-scored[i].ifp_score, i))
    # Округление вверх: на наборе из 10 молекул топ в 20 % — это 2 молекулы, а не 0.
    размер_топа = math.ceil(len(scored) * top_fraction)

    строки: list[dict[str, Any]] = [{} for _ in scored]
    for место, индекс in enumerate(порядок, start=1):
        молекула = scored[индекс]
        строки[индекс] = {
            "mol_id": молекула.mol_id,
            "ifp_score": round(молекула.ifp_score, 6),
            "ifp_score_norm": round(молекула.ifp_score_norm, 6),
            "rank": место,
            "selected": int(место <= размер_топа),
        }
    return строки
