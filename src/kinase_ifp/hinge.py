"""Частота водородных связей по позициям кармана в эталонных отпечатках KLIFS.

Задача модуля — проверка, а не выбор. Позиции шарнира 46, 47, 48 взяты из структурной
разметки KLIFS и здесь не выводятся: здесь считается, действительно ли
на этих позициях водородные связи встречаются чаще, чем на остальных.

Вопрос перестал быть формальным после измерения: у кристаллического лиганда мишени
6tgu водородных связей с шарниром нет вовсе — они приходятся на позиции 17 и 81. Одна
структура ничего не доказывает, статистика по тысячам комплексов — доказывает.

Здесь только арифметика над битовыми массивами: ни RDKit, ни ProLIF, ни путей к файлам.
Эталонные строки читает `klifs.read_fingerprint_table`, разбирает `fingerprint.bits_to_ifp`.
"""

from __future__ import annotations

from collections.abc import Iterable, Iterator
from dataclasses import dataclass

import numpy as np

from kinase_ifp.config import (
    HBOND_TYPES,
    HINGE_POSITIONS,
    KEY_POSITIONS,
    KLIFS_INTERACTION_TYPES,
    N_KLIFS_POSITIONS,
)
from kinase_ifp.fingerprint import bits_to_ifp
from kinase_ifp.similarity import as_full_ifp

# Сколько самых частых позиций попадает в сводку. Десять — чтобы участок шарнира
# (три позиции) был виден на фоне соседей, а таблица оставалась читаемой в тексте.
TOP_POSITIONS: int = 10


@dataclass(frozen=True)
class PositionStat:
    """Одна позиция кармана: номер 1..85, доля комплексов с H-связью и ранг по частоте."""

    position: int
    frequency: float
    rank: int


@dataclass(frozen=True)
class HingeComparison:
    """Сводка частотного анализа: что получилось и как это соотносится с разметкой KLIFS.

    `hinge` — позиции из `HINGE_POSITIONS`, `key` — именованные позиции из `KEY_POSITIONS`,
    `top` — `TOP_POSITIONS` самых частых позиций по убыванию частоты.
    """

    n_complexes: int
    frequencies: np.ndarray
    ranks: np.ndarray
    hinge: tuple[PositionStat, ...]
    key: tuple[tuple[str, PositionStat], ...]
    top: tuple[PositionStat, ...]


def hbond_frequencies(fingerprints: Iterable[np.ndarray]) -> tuple[np.ndarray, int]:
    """Доля комплексов с водородной связью на каждой из 85 позиций.

    Принимает последовательность полных отпечатков формы (7, 85), возвращает пару:
    массив формы (85,) со значениями от 0 до 1 и число учтённых комплексов.

    Связь засчитывается по обоим типам `HBOND_TYPES` сразу: направление (белок донор
    или акцептор) для вопроса «есть ли здесь H-связь» роли не играет.

    Отпечатки перебираются по одному, а не собираются в общий массив: эталонов KLIFS
    почти восемь тысяч, и держать их все в памяти незачем.

    Поднимает `ValueError` на пустом входе: массив нулей в этом случае неотличим
    от честного «связей нет ни на одной позиции».
    """
    строки = [KLIFS_INTERACTION_TYPES.index(тип) for тип in HBOND_TYPES]
    счётчик = np.zeros(N_KLIFS_POSITIONS, dtype=np.int64)
    всего = 0

    for отпечаток in fingerprints:
        bits = as_full_ifp(отпечаток, f"эталон №{всего + 1}")
        счётчик += bits[строки].any(axis=0)
        всего += 1

    if всего == 0:
        raise ValueError("Набор отпечатков пуст: считать частоты не по чему")
    return счётчик / всего, всего


def frequency_ranks(frequencies: np.ndarray) -> np.ndarray:
    """Ранг каждой позиции по убыванию частоты: 1 — самая частая.

    Принимает массив формы (85,), возвращает массив той же формы с целыми рангами.

    Ранжирование соревновательное: одинаковые частоты получают один и тот же ранг,
    а следующий за ними ранг пропускается. Иначе порядок между равными позициями
    определял бы `argsort`, то есть номер позиции, и в отчёте появилось бы
    несуществующее различие.
    """
    значения = _as_frequencies(frequencies)
    # Ранг = сколько позиций строго частотнее, плюс один.
    больше = (значения[:, None] < значения[None, :]).sum(axis=1)
    return np.asarray(больше + 1, dtype=int)


def compare_with_hinge(
    frequencies: np.ndarray,
    n_complexes: int,
    top_n: int = TOP_POSITIONS,
) -> HingeComparison:
    """Сводит частоты с разметкой KLIFS: шарнир, ключевые позиции и самые частые.

    Принимает массив частот (85,) и число комплексов, по которым он посчитан;
    возвращает `HingeComparison`. Поднимает `ValueError` при неверной форме входа
    или при `top_n` вне 1..85.
    """
    значения = _as_frequencies(frequencies)
    if not 1 <= top_n <= N_KLIFS_POSITIONS:
        raise ValueError(f"top_n={top_n} вне диапазона 1..{N_KLIFS_POSITIONS}")

    ranks = frequency_ranks(значения)

    def статистика(позиция: int) -> PositionStat:
        return PositionStat(
            position=позиция,
            frequency=float(значения[позиция - 1]),
            rank=int(ranks[позиция - 1]),
        )

    # При равных частотах порядок задаётся номером позиции — иначе топ менялся бы
    # от запуска к запуску, а файл в git прыгал бы без изменения данных.
    порядок = np.lexsort((np.arange(N_KLIFS_POSITIONS), -значения))
    return HingeComparison(
        n_complexes=n_complexes,
        frequencies=значения,
        ranks=ranks,
        hinge=tuple(статистика(позиция) for позиция in HINGE_POSITIONS),
        key=tuple((имя, статистика(позиция)) for имя, позиция in sorted(KEY_POSITIONS.items())),
        top=tuple(статистика(int(индекс) + 1) for индекс in порядок[:top_n]),
    )


def hinge_in_top(comparison: HingeComparison) -> tuple[PositionStat, ...]:
    """Позиции шарнира, попавшие в верхние `top_n` позиций кармана по частоте H-связей.

    Порог — вхождение в топ, а не сравнение с медианой или со средним. Медиана здесь
    бесполезна: на реальной выгрузке она равна 0.0004 (35 позиций из 85 не дают
    водородных связей ни разу), и её проходит любая позиция с единственным битом.
    Такой критерий отвечал бы «да» всегда и не различал бы ничего.
    """
    верх = {стат.position for стат in comparison.top}
    return tuple(стат for стат in comparison.hinge if стат.position in верх)


def hinge_verdict(comparison: HingeComparison) -> str:
    """Словесный вывод: сходится ли разметка шарнира с наблюдаемыми контактами.

    Три исхода, а не два. Промежуточный — не отговорка: на выгрузке KLIFS он и получается,
    и полностью меняет содержание абзаца в тексте по сравнению с любым из крайних.
    """
    попали = len(hinge_in_top(comparison))
    if попали == len(comparison.hinge):
        return "сходятся"
    if попали == 0:
        return "расходятся"
    return "сходятся частично"


def render_report(comparison: HingeComparison, source: str, filters: str) -> str:
    """Собирает текст `docs/hinge.md`: условия расчёта, сводка и таблица по 85 позициям.

    `source` — откуда взяты отпечатки, `filters` — какими фильтрами отобраны структуры.
    Оба попадают в текст: без них через неделю нельзя сказать, по чему считали.
    """
    вывод = hinge_verdict(comparison)
    попали = hinge_in_top(comparison)
    мимо = tuple(стат for стат in comparison.hinge if стат not in попали)
    размер_топа = len(comparison.top)

    подробности = (
        f"В верхние {размер_топа} позиций кармана из {N_KLIFS_POSITIONS} попали "
        + (
            ", ".join(f"{стат.position} (ранг {стат.rank})" for стат in попали)
            if попали
            else "ни одна из позиций шарнира"
        )
        + (
            "; не попали "
            + ", ".join(
                f"{стат.position} (ранг {стат.rank}, доля {стат.frequency:.3f})" for стат in мимо
            )
            if мимо
            else ""
        )
        + "."
    )

    строки: list[str] = [
        "# Частота водородных связей по позициям кармана",
        "",
        "Файл собирается командой `python scripts/hinge_positions.py`",
        "и правится только ею: руками сюда ничего не дописывают.",
        "",
        "## Что посчитано",
        "",
        f"- источник: `{source}`;",
        f"- комплексов: {comparison.n_complexes};",
        f"- отбор структур: {filters};",
        f"- величина: доля комплексов, где на позиции стоит бит `{HBOND_TYPES[0]}` "
        f"или `{HBOND_TYPES[1]}` (направление связи не различается);",
        "- ранг: место позиции по убыванию частоты, 1 — самая частая; равные частоты "
        "получают равный ранг.",
        "",
        "## Шарнир против остального кармана",
        "",
        f"Разметка KLIFS и наблюдаемые контакты **{вывод}**. {подробности}",
        "",
        "| Позиция | Доля комплексов | Ранг из 85 |",
        "|---|---|---|",
    ]
    строки += [
        f"| {стат.position} (шарнир) | {стат.frequency:.3f} | {стат.rank} |"
        for стат in comparison.hinge
    ]
    строки += [
        f"| {стат.position} ({имя}) | {стат.frequency:.3f} | {стат.rank} |"
        for имя, стат in comparison.key
    ]

    строки += [
        "",
        f"## Самые частые позиции: топ-{len(comparison.top)}",
        "",
        "| Место | Позиция | Доля комплексов |",
        "|---|---|---|",
    ]
    строки += [
        f"| {место} | {стат.position} | {стат.frequency:.3f} |"
        for место, стат in enumerate(comparison.top, start=1)
    ]

    строки += ["", "## Как это читать", ""] + _interpretation(comparison)

    строки += [
        "",
        "## Все 85 позиций",
        "",
        "| Позиция | Доля комплексов | Ранг |",
        "|---|---|---|",
    ]
    строки += [
        f"| {позиция} | {comparison.frequencies[позиция - 1]:.3f} "
        f"| {int(comparison.ranks[позиция - 1])} |"
        for позиция in range(1, N_KLIFS_POSITIONS + 1)
    ]
    return "\n".join(строки) + "\n"


def _interpretation(comparison: HingeComparison) -> list[str]:
    """Абзацы с разбором результата: что означают числа и что из них следует.

    Текст собирается здесь, а не дописывается в `docs/hinge.md` руками: файл
    переписывается при каждом запуске скрипта, и ручная правка исчезла бы молча.
    Числа подставляются из расчёта — пересказывать их в коде значило бы завести
    вторую версию тех же величин.
    """
    попали = hinge_in_top(comparison)
    мимо = tuple(стат for стат in comparison.hinge if стат not in попали)
    сильнейшая = max(comparison.hinge, key=lambda стат: стат.frequency)

    абзацы = [
        "Разметка шарнира в KLIFS структурная: участок `hinge` задан положением остатков "
        "в укладке киназы, а не их способностью образовывать водородные связи. Поэтому "
        "совпадение с наблюдаемыми контактами не обязано быть полным, и полученная "
        "картина именно такая.",
    ]

    if мимо:
        часто = ", ".join(
            f"позиция {стат.position} — {стат.frequency:.1%} комплексов" for стат in попали
        )
        редко = ", ".join(f"позиция {стат.position} — {стат.frequency:.1%}" for стат in мимо)
        абзацы.append(
            f"Связи с шарниром распределены неравномерно: {часто}, тогда как {редко}. "
            "Участие конкретного остатка зависит от того, куда обращены донор "
            "и акцептор его остова, и позиция в размеченном участке этого не определяет. "
            "**Проверить:** согласуется ли такое распределение с известной "
            "картиной связывания ингибиторов I типа с шарниром."
        )

    абзацы.append(
        f"Для метрики `hinge_hbond` отсюда не следует ничего нового: она берёт ключевые "
        f"позиции из эталонного отпечатка мишени (`key_hbond_positions`), а не из "
        f"`HINGE_POSITIONS`. Эта статистика выбор подкрепляет. У эталона "
        f"6tgu водородных связей с шарниром нет вовсе, при том что позиция "
        f"{сильнейшая.position} даёт связь в {сильнейшая.frequency:.1%} комплексов "
        f"выборки: мишень нетипична, и метрика по общему для киназ участку измеряла бы "
        f"на ней похожесть на средний киназный ингибитор, а не близость к эталону."
    )

    разделённые: list[str] = []
    for абзац in абзацы:
        if разделённые:
            разделённые.append("")
        разделённые.append(абзац)
    return разделённые


def _as_frequencies(frequencies: np.ndarray) -> np.ndarray:
    """Проверяет, что перед нами массив долей по 85 позициям."""
    значения = np.asarray(frequencies, dtype=float)
    if значения.shape != (N_KLIFS_POSITIONS,):
        raise ValueError(
            f"Ожидался массив частот формы ({N_KLIFS_POSITIONS},), получена {значения.shape}"
        )
    if not ((значения >= 0.0) & (значения <= 1.0)).all():
        raise ValueError("Частоты должны лежать в диапазоне от 0 до 1")
    return значения


def fingerprints_from_bits(bits: Iterable[str]) -> Iterator[np.ndarray]:
    """Переводит битовые строки KLIFS в отпечатки (7, 85) по одной.

    Генератор, а не список: `hbond_frequencies` перебирает вход однократно, и собирать
    восемь тысяч массивов в память незачем. Разбор строки делает `fingerprint.bits_to_ifp`,
    она же проверяет длину и алфавит.
    """
    return (bits_to_ifp(строка) for строка in bits)
