"""Подготовка лиганда к расчёту отпечатка: заряды и водороды.

Локальный набор поз и генерация в Modal обязаны готовить молекулы
одинаково. Если каждый сделает это по-своему, сравнение условий превратится
в сравнение двух протоколов подготовки, а не двух способов отбора молекул.

Подготовка состоит из двух шагов, и порядок обязателен: сначала состояние ионизации
(`normalize_charges`), потом водороды (`add_explicit_hydrogens`). Точка входа
для производителей SDF — `prepare_ligand`, которая делает оба.

**Зачем нормализация зарядов.** Кристаллический лиганд приходит из KLIFS с уже
размеченным карбоксилатом (тип `O.co2` в mol2), а сгенерированные молекулы придут
из DiffSBDD без всякой разметки — заряды расставит RDKit по валентности, и карбоксил
окажется нейтральным. Измерено на 6tgu: та же молекула по второму пути теряет
солевой мостик с каталитическим лизином (`ION+`), Танимото падает с 0.588 до 0.529,
а `ION+` входит в `SCORING_INTERACTION_TYPES` и прямо влияет на скор. Без нормализации
таблица «было/стало» сравнивала бы не только отбор молекул, но и два способа
подготовки (`docs/questions.md`, В-12).

Белок эти функции не трогают: карман приходит из KLIFS уже с водородами
(см. `pocket.load_pocket`).
"""

from __future__ import annotations

from typing import Final

from rdkit import Chem

# Группы, состояние которых при pH 7.4 определено однозначно, и правило их приведения.
#
# Список намеренно короткий. Взяты только те группы, у которых pKa отстоит от 7.4
# настолько, что состояние не зависит от окружения: карбоновые кислоты (pKa 4–5),
# сульфоновые (pKa < 1), алифатические амины (pKa ~10). Фенолы (pKa ~10 — но у
# замещённых бывает и 7), имидазолы, тетразолы и амиды сюда не входят: там состояние
# зависит от заместителей, и угадывать опаснее, чем оставить как есть.
#
# Таутомерию это не решает вовсе — она отдельная задача и в формат папки прогона не входит.

# Карбоновая кислота: C(=O)OH. Ищем именно гидроксильный кислород.
_CARBOXYLIC_ACID: Final[str] = "[CX3](=[OX1])[OX2H1]"

# Сульфоновая кислота: S(=O)(=O)OH.
_SULFONIC_ACID: Final[str] = "[SX4](=[OX1])(=[OX1])[OX2H1]"

# Алифатический амин: азот с водородами при углероде sp3. Исключены амиды (N-C=O),
# анилины (N при ароматике), нитрилы и имины, N-оксиды и уже заряженный азот.
_ALIPHATIC_AMINE: Final[str] = (
    "[NX3;H1,H2,H3;!$(N=*);!$(N#*);!$(N[!#6;!#1]);!$(Na);!$(NC=[O,N,S]);!$([N+])]"
)


# Тот же набор кислотных групп, но как готовый запрос: им `compute_ifp` проверяет,
# что молекулу пропустили через нормализацию, а не мимо неё.
UNNORMALIZED_ACID: Final = Chem.MolFromSmarts(f"[$({_CARBOXYLIC_ACID}),$({_SULFONIC_ACID})]")


class ProtonationError(RuntimeError):
    """Молекулу не удалось подготовить."""


class HydrogenError(ProtonationError):
    """Не удалось достроить явные водороды."""


class ChargeNormalizationError(ProtonationError):
    """Не удалось привести заряды к pH 7.4."""


def has_explicit_hydrogens(mol: Chem.Mol) -> bool:
    """Есть ли у молекулы хотя бы один водород как отдельный атом.

    Проверяется именно наличие атомов-водородов, а не счётчик `GetNumImplicitHs`:
    ProLIF работает с координатами, а у неявного водорода координат нет.
    """
    return any(atom.GetAtomicNum() == 1 for atom in mol.GetAtoms())


def add_explicit_hydrogens(mol: Chem.Mol) -> Chem.Mol:
    """Достраивает водороды с координатами и возвращает новую молекулу.

    Принимает молекулу с трёхмерной конформацией, возвращает её же с явными
    водородами. Исходная молекула не изменяется.

    Поднимает `HydrogenError` (подкласс `ProtonationError`), если у молекулы нет
    конформации: без координат
    достраивать водороды бессмысленно — они получат нулевые координаты, и отпечаток
    будет посчитан по молекуле, у которой все водороды сидят в начале координат.
    Расчёт при этом не падает, а тихо врёт, поэтому случай отсекается здесь.
    """
    if mol.GetNumConformers() == 0:
        raise HydrogenError(
            "У молекулы нет конформации: достраивать водороды нечему, координаты "
            "водородов получились бы нулевыми"
        )

    # addCoords=True — не украшение: без него RDKit ставит всем водородам координаты
    # (0, 0, 0), и любой расчёт взаимодействий по такой молекуле даёт мусор.
    with_hydrogens = Chem.AddHs(mol, addCoords=True)

    if not has_explicit_hydrogens(with_hydrogens):
        raise HydrogenError(
            "После AddHs у молекулы нет ни одного водорода: вероятно, все валентности "
            "уже заполнены тяжёлыми атомами — проверьте, что молекула разобрана верно"
        )
    return with_hydrogens


def _deprotonate(mol: Chem.RWMol, pattern: str) -> int:
    """Снимает водород с кислорода в группах, совпавших с SMARTS. Возвращает число правок."""
    query = Chem.MolFromSmarts(pattern)
    правок = 0
    for совпадение in mol.GetSubstructMatches(query):
        # Последний атом в обоих шаблонах — тот самый гидроксильный кислород.
        atom = mol.GetAtomWithIdx(совпадение[-1])
        if atom.GetFormalCharge() != 0:
            continue
        # Явный водород при кислороде удаляем, неявный — обнуляем счётчиком: молекула
        # может прийти и с водородами, и без них, а результат обязан быть одинаковым.
        for сосед in atom.GetNeighbors():
            if сосед.GetAtomicNum() == 1:
                mol.RemoveAtom(сосед.GetIdx())
                break
        atom.SetNumExplicitHs(0)
        atom.SetNoImplicit(True)
        atom.SetFormalCharge(-1)
        правок += 1
    return правок


def _protonate_amines(mol: Chem.RWMol) -> int:
    """Ставит +1 на алифатические амины. Возвращает число правок."""
    query = Chem.MolFromSmarts(_ALIPHATIC_AMINE)
    правок = 0
    for (индекс,) in mol.GetSubstructMatches(query):
        atom = mol.GetAtomWithIdx(индекс)
        if atom.GetFormalCharge() != 0:
            continue
        atom.SetNumExplicitHs(atom.GetTotalNumHs() + 1)
        atom.SetNoImplicit(True)
        atom.SetFormalCharge(1)
        правок += 1
    return правок


def normalize_charges(mol: Chem.Mol) -> Chem.Mol:
    """Приводит молекулу к состоянию ионизации при pH 7.4.

    Карбоновые и сульфоновые кислоты депротонируются, алифатические амины
    протонируются. Группы, у которых pKa зависит от окружения — фенолы, имидазолы,
    амиды, — не трогаются: см. комментарий к списку правил.

    Возвращает новую молекулу; исходная не изменяется. Вызывать **до**
    `add_explicit_hydrogens`: заряд меняет число водородов, которое нужно достроить.

    Поднимает `ChargeNormalizationError` (подкласс `ProtonationError`), если после
    правок молекула не проходит проверку RDKit, — молча вернуть испорченную молекулу
    здесь опаснее всего, потому что
    дальше по конвейеру она превратится не в ошибку, а в неверные числа.
    """
    editable = Chem.RWMol(mol)
    _deprotonate(editable, _CARBOXYLIC_ACID)
    _deprotonate(editable, _SULFONIC_ACID)
    _protonate_amines(editable)

    результат = editable.GetMol()
    try:
        Chem.SanitizeMol(результат)
    except (Chem.AtomValenceException, Chem.KekulizeException) as error:
        raise ChargeNormalizationError(
            f"После нормализации зарядов молекула не проходит проверку RDKit: {error}"
        ) from error
    return результат


def prepare_ligand(mol: Chem.Mol) -> Chem.Mol:
    """Готовит лиганд к расчёту отпечатка: заряды при pH 7.4, затем явные водороды.

    Это единая точка входа: и набор положений, и генерация вызывают её, а не составляющие
    шаги по отдельности. Два производителя, подготовившие молекулы по-разному, дают
    систематически разные отпечатки, и сравнение условий теряет смысл.

    Поднимает `ChargeNormalizationError` или `HydrogenError` — оба подклассы
    `ProtonationError`. Разные подклассы, а не один: производитель SDF пишет причину
    в `failures.csv`, и «нет водородов» не то же самое, что «заряды не привелись».
    """
    return add_explicit_hydrogens(normalize_charges(mol))
