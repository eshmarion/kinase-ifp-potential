"""Тесты слияния сгенерированных разделов markdown с дописанными руками.

Проверяется то, из-за чего модуль появился: `scripts/calibrate_ifp.py` собирал
`docs/calibration.md` целиком и молча стирал раздел 3 — разбор механизма расхождения
по `HYD`, дописанный руками. Пропажу раздела в длинном файле никто бы не заметил,
поэтому здесь проверяется не «функция отработала», а что чужой текст переживает
запись, что повторный прогон ничего не двигает и что раздел узнаётся по номеру,
а не по заголовку.
"""

from __future__ import annotations

import pytest

from experiments.markdown import (
    MarkdownError,
    MarkdownSection,
    merge_sections,
    split_sections,
)

ПРЕАМБУЛА = ["# Сверка отпечатка с эталоном KLIFS", "", "Посчитано 2026-09-03.", ""]

РАЗДЕЛ_1 = ["## 1. Дымовая сверка на мишени 6tgu", "", "Танимото 0.588."]
РАЗДЕЛ_2 = ["## 2. Полная сверка на выборке структур", "", "Медиана 0.358."]
РАЗДЕЛ_3 = ["## 3. Механизм расхождения по `HYD`", "", "Порог совпадает, отбор — нет."]


def собрать(*блоки: list[str]) -> str:
    """Склеивает блоки так же, как их склеивает `merge_sections`."""
    return "\n\n".join("\n".join(блок) for блок in блоки) + "\n"


class TestРазбор:
    def test_преамбула_и_разделы_разделяются(self) -> None:
        преамбула, разделы = split_sections(собрать(ПРЕАМБУЛА, РАЗДЕЛ_1, РАЗДЕЛ_2))

        assert преамбула[0] == "# Сверка отпечатка с эталоном KLIFS"
        assert [р.key for р in разделы] == ["1", "2"]
        assert разделы[0].heading == "## 1. Дымовая сверка на мишени 6tgu"

    def test_ключом_служит_номер_а_не_заголовок(self) -> None:
        """Заголовок раздела 1 несёт код мишени и меняется вместе с `--target`."""
        _, разделы = split_sections(собрать(ПРЕАМБУЛА, РАЗДЕЛ_1))

        assert разделы[0].key == "1"

    def test_заголовок_без_номера_узнаётся_по_тексту(self) -> None:
        _, разделы = split_sections("## Приложение\n\nтекст\n")

        assert разделы[0].key == "приложение"

    def test_решётки_внутри_ограждённого_блока_не_заголовок(self) -> None:
        """В `calibration.md` есть блок со SMARTS-шаблоном, и там встречается `#`."""
        текст = собрать(
            ПРЕАМБУЛА,
            ["## 1. Раздел", "", "```", "## это не заголовок", "```", "", "хвост раздела"],
        )

        _, разделы = split_sections(текст)

        assert [р.key for р in разделы] == ["1"]
        assert "## это не заголовок" in разделы[0].lines

    def test_повторный_ключ_в_файле_отвергается(self) -> None:
        текст = собрать(ПРЕАМБУЛА, РАЗДЕЛ_1, ["## 1. Он же второй раз", "", "текст"])

        with pytest.raises(MarkdownError, match="1"):
            split_sections(текст)

    def test_файл_без_разделов_весь_уходит_в_преамбулу(self) -> None:
        преамбула, разделы = split_sections("# Заголовок\n\nтекст\n")

        assert разделы == []
        assert "текст" in преамбула


class TestСлияние:
    def test_дописанный_руками_раздел_сохраняется_дословно(self) -> None:
        старый = собрать(ПРЕАМБУЛА, РАЗДЕЛ_1, РАЗДЕЛ_2, РАЗДЕЛ_3)
        новый_первый = ["## 1. Дымовая сверка на мишени 6tgu", "", "Танимото 0.590."]

        итог = merge_sections(старый, [новый_первый], preamble=ПРЕАМБУЛА)

        assert "\n".join(РАЗДЕЛ_3) in итог
        assert "\n".join(РАЗДЕЛ_2) in итог
        assert "Танимото 0.590." in итог
        assert "Танимото 0.588." not in итог

    def test_порядок_разделов_не_меняется(self) -> None:
        старый = собрать(ПРЕАМБУЛА, РАЗДЕЛ_1, РАЗДЕЛ_2, РАЗДЕЛ_3)

        итог = merge_sections(старый, [РАЗДЕЛ_1], preamble=ПРЕАМБУЛА)

        _, разделы = split_sections(итог)
        assert [р.key for р in разделы] == ["1", "2", "3"]

    def test_преамбула_старого_файла_не_трогается(self) -> None:
        """Дата в преамбуле относится к разделу 2; прогон разделов 1 и 4 её не сдвигает."""
        старый = собрать(ПРЕАМБУЛА, РАЗДЕЛ_1)
        другая = ["# Сверка", "", "Посчитано 2026-09-14.", ""]

        итог = merge_sections(старый, [РАЗДЕЛ_1], preamble=другая)

        assert "Посчитано 2026-09-03." in итог
        assert "2026-09-14" not in итог

    def test_своя_преамбула_пишется_только_при_создании_файла(self) -> None:
        итог = merge_sections(None, [РАЗДЕЛ_1], preamble=ПРЕАМБУЛА)

        assert итог.startswith("# Сверка отпечатка с эталоном KLIFS")
        assert "Посчитано 2026-09-03." in итог

    def test_незнакомый_раздел_дописывается_в_конец(self) -> None:
        старый = собрать(ПРЕАМБУЛА, РАЗДЕЛ_1, РАЗДЕЛ_2, РАЗДЕЛ_3)
        раздел_4 = ["## 4. Сверка на перевыбранной выборке", "", "Медиана 0.372."]

        итог = merge_sections(старый, [раздел_4], preamble=ПРЕАМБУЛА)

        _, разделы = split_sections(итог)
        assert [р.key for р in разделы] == ["1", "2", "3", "4"]

    def test_заголовок_с_другой_мишенью_заменяет_тот_же_раздел(self) -> None:
        """Сравнение по тексту заголовка дало бы в файле два первых раздела."""
        старый = собрать(ПРЕАМБУЛА, РАЗДЕЛ_1, РАЗДЕЛ_2)
        другая_мишень = ["## 1. Дымовая сверка на мишени 5lvm", "", "Танимото 0.500."]

        итог = merge_sections(старый, [другая_мишень], preamble=ПРЕАМБУЛА)

        _, разделы = split_sections(итог)
        assert [р.key for р in разделы] == ["1", "2"]
        assert "5lvm" in итог
        assert "6tgu" not in итог

    def test_повторное_слияние_побайтово_равно_однократному(self) -> None:
        старый = собрать(ПРЕАМБУЛА, РАЗДЕЛ_1, РАЗДЕЛ_2, РАЗДЕЛ_3)

        один = merge_sections(старый, [РАЗДЕЛ_1], preamble=ПРЕАМБУЛА)
        два = merge_sections(один, [РАЗДЕЛ_1], preamble=ПРЕАМБУЛА)

        assert один == два

    def test_хвостовые_пустые_строки_не_копятся(self) -> None:
        старый = собрать(ПРЕАМБУЛА, [*РАЗДЕЛ_1, "", "", ""], РАЗДЕЛ_2)

        итог = merge_sections(старый, [РАЗДЕЛ_2], preamble=ПРЕАМБУЛА)

        assert "\n\n\n" not in итог
        assert итог.endswith("Медиана 0.358.\n")

    def test_файл_кончается_ровно_одним_переводом_строки(self) -> None:
        итог = merge_sections(собрать(ПРЕАМБУЛА, РАЗДЕЛ_1), [РАЗДЕЛ_1], preamble=ПРЕАМБУЛА)

        assert итог.endswith("\n")
        assert not итог.endswith("\n\n")

    def test_раздел_без_заголовка_отвергается(self) -> None:
        with pytest.raises(MarkdownError, match="## "):
            merge_sections(None, [["просто текст"]], preamble=ПРЕАМБУЛА)

    def test_два_сгенерированных_раздела_с_одним_ключом_отвергаются(self) -> None:
        with pytest.raises(MarkdownError, match="1"):
            merge_sections(None, [РАЗДЕЛ_1, ["## 1. Он же", "", "текст"]], preamble=ПРЕАМБУЛА)


def test_раздел_знает_свой_ключ_и_строки() -> None:
    раздел = MarkdownSection(key="2", heading=РАЗДЕЛ_2[0], lines=tuple(РАЗДЕЛ_2))

    assert раздел.lines[0] == раздел.heading
