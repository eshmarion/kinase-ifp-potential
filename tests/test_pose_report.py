"""Бенчмарк набора поз: числа раздела 5.2 получают машинный источник.

Проверяется не «код отработал», а что отчёт говорит ровно то, что измерено, и что
он отказывается там, где утверждение построить нельзя. Отдельно закреплено число,
делящее максимум скора: именно оно отличает «скор нативной позы выше всех»
от «ранг 1 достался ей по правилу ничьих».
"""

from __future__ import annotations

import math
from pathlib import Path

import pytest

from evaluation.stats import StatsError, spearman, spearman_permutation_p
from experiments.pose_report import PoseReportError, записать, строки
from experiments.results_io import Строка, как_текст

КОРЕНЬ = Path(__file__).resolve().parents[1]
НАБОР_ПОЗ = КОРЕНЬ / "runs" / "2026-08-24-6tgu-s0-n100"
ГЕНЕРАЦИЯ = КОРЕНЬ / "runs" / "2026-08-24-6tgu-s0-n100-seed1"


def _значения(собранные: list[Строка]) -> dict[str, float]:
    return {с.показатель: с.значение for с in собранные}


@pytest.fixture(scope="module")
def отчёт() -> dict[str, float]:
    if not НАБОР_ПОЗ.is_dir():
        pytest.skip(f"нет прогона {НАБОР_ПОЗ.name}")
    return _значения(строки(НАБОР_ПОЗ))


def test_связь_скора_с_отклонением_отрицательна_и_велика(отчёт: dict[str, float]) -> None:
    ро = отчёт["корреляция скора с отклонением"]
    assert ро < -0.7, ро
    assert отчёт["поз в наборе"] == 100


def test_уровень_значимости_не_ноль(отчёт: dict[str, float]) -> None:
    """Ноль означал бы «невозможно», а измерено «меньше одной перестановки из десяти тысяч»."""
    уровень = отчёт["уровень значимости корреляции"]
    assert 0.0 < уровень <= 1.0
    assert уровень == pytest.approx(1 / (отчёт["перестановок в тесте"] + 1), rel=1e-6)


def test_ранг_нативной_позы_показан_вместе_с_числом_делящих_максимум(
    отчёт: dict[str, float],
) -> None:
    """Ранг 1 даёт правило ничьих, и одно число об этом умалчивает."""
    assert отчёт["ранг нативной позы"] == 1
    assert отчёт["скор нативной позы"] == отчёт["наибольший скор в наборе"]
    assert отчёт["поз с наибольшим скором"] > 1, (
        "если максимум делит одна поза, утверждение о ранге держится на скоре, "
        "и оговорка про ничьи не нужна — проверь, не изменился ли набор"
    )


def test_доля_ключевой_связи_падает_с_отклонением(отчёт: dict[str, float]) -> None:
    ближние = отчёт["доля с ключевой связью, < 1 Å"]
    дальние = отчёт["доля с ключевой связью, > 2 Å"]
    assert ближние > дальние
    assert отчёт["поз в бине < 1 Å"] + отчёт["поз в бине 1–2 Å"] + отчёт["поз в бине > 2 Å"] == 100


def test_генерация_отвергается_а_не_считается_молча() -> None:
    """У сгенерированной молекулы эталонной позы нет — корреляции взяться неоткуда."""
    if not ГЕНЕРАЦИЯ.is_dir():
        pytest.skip(f"нет прогона {ГЕНЕРАЦИЯ.name}")
    with pytest.raises(PoseReportError, match="эталонной позы нет"):
        строки(ГЕНЕРАЦИЯ)


def test_отчёт_пишется_обоими_файлами(tmp_path: Path, отчёт: dict[str, float]) -> None:
    путь_md, путь_csv = записать(строки(НАБОР_ПОЗ), tmp_path)
    assert путь_md.is_file() and путь_csv.is_file()
    assert b"\r\n" not in путь_csv.read_bytes()
    assert "| поз в наборе | 100 | поз |" in путь_md.read_text(encoding="utf-8")


# --- сами статистики -------------------------------------------------------------


def test_спирмен_на_известном_ответе() -> None:
    """Монотонные ряды дают ±1, независимо от того, линейны ли они."""
    assert spearman([1, 2, 3, 4], [10, 20, 30, 40]) == pytest.approx(1.0)
    assert spearman([1, 2, 3, 4], [1, 4, 9, 16]) == pytest.approx(1.0)
    assert spearman([1, 2, 3, 4], [40, 30, 20, 10]) == pytest.approx(-1.0)


def test_спирмен_считает_связи_средним_рангом() -> None:
    """Известный ответ: две связанные пары дают ровно 0.5."""
    assert spearman([1, 1, 2, 2], [1, 2, 1, 2]) == pytest.approx(0.0)
    assert spearman([1, 2, 3, 4], [1, 2, 2, 3]) == pytest.approx(0.9486832980505138)


def test_постоянный_ряд_даёт_не_ноль_а_неопределённость() -> None:
    """Ноль читался бы как измеренное отсутствие связи, а связи не из чего посчитать."""
    assert math.isnan(spearman([1, 2, 3], [5, 5, 5]))


def test_ряды_разной_длины_отвергаются() -> None:
    with pytest.raises(StatsError, match="разной длины"):
        spearman([1, 2, 3], [1, 2])


def test_перестановочный_уровень_воспроизводим_по_сиду() -> None:
    x = [1, 2, 3, 4, 5, 6, 7, 8]
    y = [2, 1, 4, 3, 6, 5, 8, 7]
    первый = spearman_permutation_p(x, y, resamples=500, seed=7)
    второй = spearman_permutation_p(x, y, resamples=500, seed=7)
    assert первый == второй


def test_перестановочный_уровень_не_бывает_нулём() -> None:
    """Сдвинутая оценка: «ни одной перестановки» — это граница, а не невозможность."""
    x = list(range(20))
    y = list(range(20))
    уровень, перестановок = spearman_permutation_p(x, y, resamples=200, seed=1)
    assert уровень == pytest.approx(1 / 201)
    assert перестановок == 200


def test_перестановочный_тест_на_постоянном_ряде_отказывает() -> None:
    with pytest.raises(StatsError, match="постоянна"):
        spearman_permutation_p([1, 2, 3], [5, 5, 5])


def test_неприменимая_величина_печатается_прочерком() -> None:
    """Пустой бин даёт `nan`, и он обязан читаться как «неприменимо», а не как ноль."""
    assert как_текст(float("nan")) == "—"
    assert как_текст(0.0) == "0"


def test_малое_число_печатается_научной_записью_а_не_нулём() -> None:
    """Четыре знака превращали p меньше 0.0001 в «0.0000».

    Это не округление, а подмена значения: нулём p не бывает. Текст такие величины
    пишет научной записью, и сверка чисел их не подтверждала — в источнике стоял
    ноль. Порог совпадает с точностью обычной записи: ниже неё четыре знака
    информации уже не несут.
    """
    assert как_текст(4.1e-10) == "4.100000e-10"
    # Значащих семь: сверка огрубляет источник до точности текста, и записанное
    # короче расходится с текстом на ровной половине — 1.4496·10⁻⁴ против 1.4·10⁻⁴.
    assert как_текст(0.00014496) == "1.449600e-04"
    # Обычные величины запись не трогает: четыре знака у них ничего не теряют.
    assert как_текст(0.0001) == "0.0001"
    assert как_текст(0.2101) == "0.2101"
    assert как_текст(0.0065) == "0.0065"
