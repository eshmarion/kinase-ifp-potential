"""Тесты разбора альтернативных положений атомов.

Проверяется не «функция отработала», а два утверждения, на которых стоит решение:
насколько далеко расходятся конформеры и совпадает ли выбор «первый по алфавиту»
с выбором «мажорный».
"""

from __future__ import annotations

import pytest

from kinase_ifp.alternates import AlternatesError, read_alternates

# Остаток с двумя положениями: атом CB смещён на 3 Å по x, атом CG — на 4 Å по y.
# Заселённости заданы так, что мажорный конформер — B, то есть правило «берём A»
# с ним расходится.
ДВА_ПОЛОЖЕНИЯ = """\
ATOM      1  N   HIS A 161      10.000  10.000  10.000  1.00 20.00           N
ATOM      2  CB AHIS A 161      11.000  10.000  10.000  0.40 20.00           C
ATOM      3  CB BHIS A 161      14.000  10.000  10.000  0.60 20.00           C
ATOM      4  CG AHIS A 161      12.000  10.000  10.000  0.40 20.00           C
ATOM      5  CG BHIS A 161      12.000  14.000  10.000  0.60 20.00           C
"""


def test_расхождение_берётся_наибольшее_по_одноимённым_атомам() -> None:
    """Вопрос «разворачивается ли остаток» решает самая подвижная часть, а не средняя."""
    группы = read_alternates(ДВА_ПОЛОЖЕНИЯ)

    assert len(группы) == 1
    assert группы[0].label == "HIS161"
    assert группы[0].shift == pytest.approx(4.0)
    assert группы[0].pairs == 2


def test_мажорный_конформер_определяется_заселённостью() -> None:
    """Правило «берём A» и правило «берём мажорный» совпадают не всегда."""
    группа = read_alternates(ДВА_ПОЛОЖЕНИЯ)[0]

    assert группа.occupancy == {"A": 0.40, "B": 0.60}
    assert группа.major == "B"
    assert not группа.first_is_major


def test_атомы_без_метки_альтернативы_не_дают_группы() -> None:
    """Остаток, у которого одно положение, альтернативой не является."""
    обычный = "ATOM      1  N   ALA A   1      10.000  10.000  10.000  1.00 20.00           N\n"

    assert read_alternates(обычный) == []


def test_вторая_модель_не_читается() -> None:
    """В записях ЯМР моделей десятки, и альтернативы там означают другое."""
    текст = ДВА_ПОЛОЖЕНИЯ + "ENDMDL\n" + ДВА_ПОЛОЖЕНИЯ.replace("HIS A 161", "HIS A 999")

    метки = [г.label for г in read_alternates(текст)]

    assert метки == ["HIS161"]


def test_короткая_запись_отвергается() -> None:
    """Обрезанная строка PDB — это не «ноль альтернатив», а нечитаемый файл."""
    with pytest.raises(AlternatesError, match="координаты не читаются"):
        read_alternates("ATOM      1  CB AHIS A 161      10.000\n")


def test_группы_отсортированы_по_убыванию_расхождения() -> None:
    """Отчёт начинается с того, ради чего измерение и делается."""
    малое = ДВА_ПОЛОЖЕНИЯ.replace("HIS A 161", "SER A  10").replace(
        "14.000  10.000", "11.500  10.000"
    )
    группы = read_alternates(ДВА_ПОЛОЖЕНИЯ + малое)

    assert [г.shift for г in группы] == sorted((г.shift for г in группы), reverse=True)
