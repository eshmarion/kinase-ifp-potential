"""Статистика оптимизации поз дискретным потенциалом.

    docker compose run --rm dev python scripts/pose_optimization_stats.py

Читает таблицы `results/pose_optimization-*.csv`, которые пишет
`scripts/optimize_poses.py`, и считает по ним то, чего в сводках нет: парные тесты,
сравнение с отрицательным контролем и доверительные интервалы.

Почему тесты именно такие. Сравнение «до и после» — **парное**: это одна и та же
молекула в двух состояниях, поэтому берётся критерий Уилкоксона для связанных выборок,
а не Манна—Уитни для независимых. Опыт против контроля — тоже парное сравнение: та же
молекула оптимизируется к настоящему эталону и к перемешанному, поэтому перестановочный
тест меняет знак внутри пары, а не перемешивает две выборки. Интервалы — бутстрэп,
потому что распределение приростов дискретно и на нормальность не похоже.
"""
import csv
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
from scipy.stats import binomtest, wilcoxon

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from experiments.layout import RUN_JSON  # noqa: E402
from experiments.measurements import upsert_measurements  # noqa: E402
from experiments.summaries import optimization_stat_measurements  # noqa: E402
from kinase_ifp.config import MEASUREMENTS_CSV, RUNS_DIR  # noqa: E402

Р = Path("results")
ПРОГОН = sys.argv[1] if len(sys.argv) > 1 else "2026-08-24-6tgu-s0-n100"

# Числа тестов идут не только в консоль, но и в реестр измерений: без машинного
# источника `scripts/check_numbers.py` их не подтверждает, и написанный по ним текст
# приходится откатывать.
ПАСПОРТ = json.loads((RUNS_DIR / ПРОГОН / RUN_JSON).read_text(encoding="utf-8"))
# Мишень берётся из паспорта, а не из имени папки: имя разбирается позиционно
# и рано или поздно уводит расчёт на чужую мишень (правило `runs.target_for_run`).
МИШЕНЬ = ПАСПОРТ["target"]["pdb_id"]
КОГДА = datetime.now(timezone.utc).date().isoformat()
КОМАНДА = f"python scripts/pose_optimization_stats.py {ПРОГОН}"
ИЗМЕРЕНИЯ: list = []


def записать(метка: str, тест: str, сводка: dict[str, float], пояснение: str = "") -> None:
    """Складывает сводку одного теста в реестр под ключом `<прогон>:<метка>:<тест>`.

    Третья часть ключа нужна потому, что на одном условии считается несколько разных
    тестов, а `effect`, `p_value` и `pairs` у каждого свои: без неё они перезаписали бы
    друг друга, и в реестре остался бы последний посчитанный.
    """
    ИЗМЕРЕНИЯ.extend(
        optimization_stat_measurements(
            МИШЕНЬ,
            f"{ПРОГОН}:{метка}:{тест}",
            сводка,
            measured_utc=КОГДА,
            source=КОМАНДА,
            notes=пояснение,
        )
    )

def читать(метка):
    путь = Р / f"pose_optimization-{ПРОГОН}-{метка}.csv"
    with путь.open(encoding="utf-8") as поток:
        строки = list(csv.DictReader(поток))
    return {к: np.array([float(с[к]) for с in строки]) for к in строки[0] if к != "mol_id"}

# Метки условий: набор типов, отрицательный контроль и вариант потенциала. Вариант
# `clash` (М1) идёт наравне с базовым, потому что через протокол его прогоняют целиком,
# а не только по целевому скору; вариант `weighted` (М2) сюда не включён — он
# закрыт по итогам начальной проверки.
УСЛОВИЯ: tuple[str, ...] = (
    "scoring6",
    "all7",
    "scoring6-control",
    "all7-control",
    "all7-clash",
    "all7-control-clash",
    # Веса члена клэша из перебора значений. Контроля у них нет и не нужно: перебор
    # отвечает на вопрос «какой вес брать», а не «лучше ли потенциал контроля».
    # Без них колонка приростов таблицы 2 «Материалов и методов» не имела источника:
    # прирост — разность двух чисел сводки, а разности реестр не хранит, и сверка
    # подтверждала её случайно совпавшим значением чужой мишени.
    "all7-clash-w0.1",
    "all7-clash-w0.5",
    "all7-clash-w2",
)

# Пары «опыт — контроль» для тестов против отрицательного контроля. Список один
# на оба теста: раньше он был записан дважды, и добавление варианта потребовало бы
# править обе копии, а разойтись они могли бы незаметно.
ПАРЫ: dict[str, tuple[str, str]] = {
    "6 типов": ("scoring6", "scoring6-control"),
    "7 типов": ("all7", "all7-control"),
    "7 типов, М1": ("all7-clash", "all7-control-clash"),
}

доступные = [м for м in УСЛОВИЯ if (Р / f"pose_optimization-{ПРОГОН}-{м}.csv").is_file()]
условия = {м: читать(м) for м in доступные}
print(f"прогон {ПРОГОН}, условий {len(условия)}: {', '.join(доступные)}")

def бутстрэп(значения, функция=np.median, n=10000, seed=0):
    rng = np.random.default_rng(seed)
    выборки = rng.choice(значения, size=(n, len(значения)), replace=True)
    оценки = функция(выборки, axis=1)
    return np.percentile(оценки, [2.5, 97.5])

print("=== 1. Парный тест Уилкоксона: до и после оптимизации (одни и те же молекулы) ===")
for метка, д in условия.items():
    for величина in ("score", "tanimoto"):
        до, после = д[f"{величина}_before"], д[f"{величина}_after"]
        приросты = после - до
        ненулевые = приросты[приросты != 0]
        if len(ненулевые) == 0:
            print(f"{метка:18s} {величина:9s}: все приросты нулевые, тест невозможен")
            continue
        t = wilcoxon(до, после, zero_method="wilcox", alternative="less")
        ди = бутстрэп(приросты, np.mean)
        print(f"{метка:18s} {величина:9s}: прирост среднее {приросты.mean():+.4f} "
              f"ДИ95 [{ди[0]:+.4f}, {ди[1]:+.4f}], Уилкоксон p={t.pvalue:.2e}, "
              f"ненулевых пар {len(ненулевые)}")
        записать(
            метка,
            f"paired_{величина}",
            {
                "effect": float(приросты.mean()),
                "p_value": float(t.pvalue),
                "pairs": float(len(ненулевые)),
                "ci_low": float(ди[0]),
                "ci_high": float(ди[1]),
                "molecules": float(len(до)),
                "before_median": float(np.median(до)),
                "after_median": float(np.median(после)),
            },
            "парный Уилкоксон, односторонний; интервал — бутстрэп среднего прироста",
        )

print("\n=== 2. Доля улучшившихся молекул против контроля (точный тест) ===")
пары = {и: (о, к) for и, (о, к) in ПАРЫ.items() if о in условия and к in условия}
for типы, (опыт, контроль) in пары.items():
    о = условия[опыт]
    к = условия[контроль]
    улучш_о = int((о["score_after"] > о["score_before"]).sum())
    улучш_к = int((к["score_after"] > к["score_before"]).sum())
    # Контроль задаёт ожидаемую долю «улучшений без сигнала», опыт сравнивается с ней.
    доля_к = max(улучш_к / len(к["score_after"]), 1e-9)
    t = binomtest(улучш_о, len(о["score_after"]), доля_к, alternative="greater")
    # Знаменатели печатаются фактические, а не «из 100»: в прогонах генерации молекул
    # меньше запрошенного (99, 98, 95 из 100), и зашитая сотня врала бы в тексте.
    print(f"{типы}: улучшилось {улучш_о}/{len(о['score_after'])}, "
          f"в контроле {улучш_к}/{len(к['score_after'])}, "
          f"биномиальный p={t.pvalue:.2e}")
    записать(
        опыт,
        "binomial_improved",
        {
            "effect": улучш_о / len(о["score_after"]),
            "p_value": float(t.pvalue),
            "pairs": float(len(о["score_after"])),
            "improved": float(улучш_о),
            "improved_control": float(улучш_к),
            "molecules_control": float(len(к["score_after"])),
        },
        f"доля улучшившихся против контроля {контроль}; точный биномиальный тест",
    )

print("\n=== 3. Перестановочный тест: прирост Танимото опыт против контроля ===")
rng = np.random.default_rng(20260918)
пары = {и: (о, к) for и, (о, к) in ПАРЫ.items() if о in условия and к in условия}
for типы, (опыт, контроль) in пары.items():
    о = условия[опыт]["tanimoto_after"] - условия[опыт]["tanimoto_before"]
    к = условия[контроль]["tanimoto_after"] - условия[контроль]["tanimoto_before"]
    # Пары связаны: одна и та же молекула в опыте и в контроле, поэтому перестановка
    # знака внутри пары, а не перемешивание двух независимых выборок.
    разница = о - к
    наблюдено = разница.mean()
    выборка = rng.choice([-1.0, 1.0], size=(20000, len(разница)))
    распределение = (выборка * разница).mean(axis=1)
    p = float((распределение >= наблюдено).mean())
    ди = бутстрэп(разница, np.mean, seed=1)
    print(f"{типы}: прирост опыта минус контроля {наблюдено:+.4f} "
          f"ДИ95 [{ди[0]:+.4f}, {ди[1]:+.4f}], перестановочный p={max(p, 1/20000):.1e}")
    записать(
        опыт,
        "permutation_tanimoto",
        {
            "effect": float(наблюдено),
            # Ноль перестановок из 20000 означает «меньше 1/20000», а не «ровно ноль»:
            # записанный нулём, такой уровень значимости выглядел бы точным.
            "p_value": max(p, 1 / 20000),
            "pairs": float(len(разница)),
            "ci_low": float(ди[0]),
            "ci_high": float(ди[1]),
            "permutations": 20000.0,
        },
        f"перестановочный тест против контроля {контроль}; знак меняется внутри пары",
    )

print("\n=== 4. Физичность: минимальное расстояние до белка ===")
for метка, д in условия.items():
    до, после = д["min_distance_before"], д["min_distance_after"]
    ухудшилось = int((после < до - 1e-9).sum())
    if (после != до).any():
        t = wilcoxon(до, после, zero_method="wilcox", alternative="less")
        p = f"{t.pvalue:.2e}"
    else:
        p = "нет изменений"
    print(
        f"{метка:18s}: медиана {np.median(до):.2f} -> {np.median(после):.2f} A, "
        f"ухудшилось {ухудшилось}/{len(до)}, Уилкоксон p={p}"
    )
    if (после != до).any():
        записать(
            метка,
            "paired_min_distance",
            {
                "effect": float(np.median(после) - np.median(до)),
                "p_value": float(t.pvalue),
                "pairs": float(int((после != до).sum())),
                "before_median": float(np.median(до)),
                "after_median": float(np.median(после)),
                "worsened": float(ухудшилось),
                # Крайние значения исходного набора: «лучшая молекула подходит
                # к белку на столько-то» — довод «Материалов и методов» о режиме
                # задания кармана. Медиана его не заменяет: утверждение про набор
                # целиком («ни одна не дотягивает до порога») проверяется максимумом,
                # а не серединой.
                "before_max": float(np.max(до)),
                "before_min": float(np.min(до)),
            },
            "минимальное расстояние до белка; растёт и в контроле — это свойство "
            "правила отбора шагов, а не потенциала; before_max — "
            "лучшая молекула набора, before_min — худшая",
        )

print("\n=== 5. Смещение позы ===")
for метка, д in условия.items():
    r = д["rmsd_shift"]
    на_пределе = float((r > 1.45).mean())
    print(f"{метка:18s}: медиана {np.median(r):.2f} A, доля на пределе {на_пределе:.2f}")

print("\n=== 6. Ключевая водородная связь: точный критерий Макнемара ===")
for метка, д in условия.items():
    до, после = д["hbond_before"].astype(bool), д["hbond_after"].astype(bool)
    появилась = int((~до & после).sum())
    исчезла = int((до & ~после).sum())
    несогласных = появилась + исчезла
    доля_до, доля_после = float(до.mean()), float(после.mean())
    if несогласных == 0:
        print(f"{метка:18s}: доля {доля_до:.3f} -> {доля_после:.3f}, несогласных пар нет")
        continue
    # Точный вариант критерия Макнемара: при верной нулевой гипотезе каждая несогласная
    # пара с равной вероятностью идёт в любую сторону, поэтому тест биномиальный на долю
    # 0.5 среди них. Уилкоксон здесь неприменим: величина двоичная, и ранги вырождаются.
    критерий = binomtest(появилась, несогласных, 0.5, alternative="greater")
    ди = бутстрэп(после.astype(float) - до.astype(float), np.mean, seed=2)
    print(
        f"{метка:18s}: доля {доля_до:.3f} -> {доля_после:.3f}, появилась у {появилась}, "
        f"исчезла у {исчезла}, Макнемар p={критерий.pvalue:.2e}, "
        f"ДИ95 разности [{ди[0]:+.3f}, {ди[1]:+.3f}]"
    )
    записать(
        метка,
        "mcnemar_hbond",
        {
            "effect": доля_после - доля_до,
            "p_value": float(критерий.pvalue),
            "pairs": float(несогласных),
            "fraction_before": доля_до,
            "fraction_after": доля_после,
            "gained": float(появилась),
            "lost": float(исчезла),
            "molecules": float(len(до)),
            "ci_low": float(ди[0]),
            "ci_high": float(ди[1]),
        },
        "доля молекул с ключевой H-связью по правилам KLIFS; точный критерий Макнемара, "
        "интервал — бутстрэп разности долей",
    )
# Запись в реестр идёт одним вызовом в конце: при ошибке посреди расчёта в файл
# не попадёт половина сводок, которую потом не отличить от полной.
if ИЗМЕРЕНИЯ:
    upsert_measurements(ИЗМЕРЕНИЯ, MEASUREMENTS_CSV)
    print(f"\nв реестр {MEASUREMENTS_CSV}: строк {len(ИЗМЕРЕНИЯ)}")

