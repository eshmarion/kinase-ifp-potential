"""Сравнение вариантов построения потенциала на одном прогоне.

    docker compose run --rm dev python scripts/compare_potentials.py --run <имя прогона>

Читает таблицы `results/pose_optimization-<прогон>-<метка>.csv`, которые пишет
`scripts/optimize_poses.py`, и сводит варианты в одну таблицу. Ничего не считает заново:
все числа уже лежат в таблицах по молекулам, и пересчёт их здесь разошёлся бы
с источником при первой же правке.

Сравнение идёт **по базовой колонке `score_*`**, одинаковой у всех вариантов, а не
по `objective_*`: последняя у каждого варианта своя, и сравнивать её между вариантами
всё равно что сравнивать метры с килограммами.

Парные тесты считаются на общем наборе молекул: варианты обрабатывают один и тот же
прогон, поэтому строки сопоставляются по `mol_id`, а не по порядку.
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

import numpy as np
from scipy import stats

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

РЕЗУЛЬТАТЫ = Path("results")

# Порядок вариантов в отчёте: базовый первым, модификации следом.
ВАРИАНТЫ: tuple[tuple[str, str], ...] = (
    ("", "М0 дискретный"),
    ("-clash", "М1 член клэша"),
    ("-weighted", "М2 взвешенный"),
)


def таблица_докинга(run: str, вариант: str) -> Path | None:
    """Путь к таблице докинга варианта, если она есть.

    Базовый вариант ищется под двумя именами: без суффикса и с `-base`. Расхождение
    историческое — первые расчёты шли до появления ключа `--label`, и переименовывать
    готовые таблицы значило бы рвать ссылки на них из отчётов.
    """
    имена = ["", "-base"] if вариант == "base" else [f"-{вариант}"]
    for имя in имена:
        путь = РЕЗУЛЬТАТЫ / f"docking-{run}{имя}.csv"
        if путь.is_file():
            return путь
    return None


def прочитать(путь: Path) -> dict[str, dict[str, float]]:
    """Таблица по молекулам как отображение `mol_id` → числа строки."""
    с = {}
    with путь.open(encoding="utf-8", newline="") as поток:
        for строка in csv.DictReader(поток):
            с[строка["mol_id"]] = {
                к: float(з) for к, з in строка.items() if к != "mol_id" and з != ""
            }
    return с


def main() -> int:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--run", required=True, help="имя папки прогона")
    разбор.add_argument("--types", default="all7", choices=("all7", "scoring6"))
    разбор.add_argument(
        "--clash-suffix",
        default="",
        help="суффикс веса у варианта clash, например -w0.5",
    )
    аргументы = разбор.parse_args()

    таблицы: dict[str, dict[str, dict[str, float]]] = {}
    for суффикс, имя in ВАРИАНТЫ:
        полный = суффикс + (аргументы.clash_suffix if суффикс == "-clash" else "")
        путь = РЕЗУЛЬТАТЫ / f"pose_optimization-{аргументы.run}-{аргументы.types}{полный}.csv"
        if not путь.is_file():
            print(f"нет таблицы {путь.name}, вариант «{имя}» пропущен", file=sys.stderr)
            continue
        таблицы[имя] = прочитать(путь)

    if not таблицы:
        print("не найдено ни одной таблицы", file=sys.stderr)
        return 1

    общие = sorted(set.intersection(*(set(т) for т in таблицы.values())))
    print(f"прогон {аргументы.run}, типов {аргументы.types}, общих молекул {len(общие)}\n")

    базовое_имя = ВАРИАНТЫ[0][1]
    print(
        f"{'вариант':16s} {'скор до':>8s} {'скор после':>11s} {'прирост':>8s} "
        f"{'улучш':>6s} {'дист. после':>12s} {'ближе 2.55':>11s} {'сдвиг':>7s}"
    )
    сводка: dict[str, np.ndarray] = {}
    for имя, таблица in таблицы.items():
        до = np.array([таблица[m]["score_before"] for m in общие])
        после = np.array([таблица[m]["score_after"] for m in общие])
        дист = np.array([таблица[m]["min_distance_after"] for m in общие])
        сдвиг = np.array([таблица[m]["rmsd_shift"] for m in общие])
        сводка[имя] = после
        print(
            f"{имя:16s} {до.mean():8.3f} {после.mean():11.3f} "
            f"{после.mean() - до.mean():+8.3f} {int((после > до).sum()):6d} "
            f"{np.median(дист):11.3f} {int((дист < 2.55).sum()):11d} {np.median(сдвиг):7.3f}"
        )

    дист_до = np.array([таблицы[базовое_имя][m]["min_distance_before"] for m in общие])
    print(
        f"\nисходные молекулы: медиана расстояния {np.median(дист_до):.3f} A, "
        f"ближе 2.55 A — {int((дист_до < 2.55).sum())} из {len(общие)}"
    )

    print("\n=== парные тесты против базового варианта (базовый скор) ===")
    for имя, значения in сводка.items():
        if имя == базовое_имя:
            continue
        тест = stats.wilcoxon(значения, сводка[базовое_имя], zero_method="zsplit")
        разница = значения.mean() - сводка[базовое_имя].mean()
        print(f"{имя:16s} разница среднего {разница:+.4f}, Уилкоксон p = {тест.pvalue:.3g}")

    print("\n=== расстояние до белка: парные тесты против базового ===")
    for имя, таблица in таблицы.items():
        if имя == базовое_имя:
            continue
        свои = np.array([таблица[m]["min_distance_after"] for m in общие])
        базовые = np.array([таблицы[базовое_имя][m]["min_distance_after"] for m in общие])
        тест = stats.wilcoxon(свои, базовые, zero_method="zsplit")
        print(
            f"{имя:16s} медиана {np.median(свои):.3f} против {np.median(базовые):.3f} A, "
            f"p = {тест.pvalue:.3g}"
        )

    сравнить_докинг(аргументы.run)
    return 0


def сравнить_докинг(run: str) -> None:
    """Прямое парное сравнение вариантов по энергии Vina, если таблицы докинга есть.

    До сих пор каждый вариант сравнивался с **исходными** молекулами, и вопрос «который
    из вариантов портит энергию меньше» оставался без прямого ответа: два сравнения
    с общей точкой отсчёта не заменяют сравнения между собой. Здесь тест парный —
    молекулы одни и те же, меняется только потенциал, которым двигали позу.
    """
    доступные: dict[str, dict[str, dict[str, float]]] = {}
    for вариант, имя in (("base", "М0 дискретный"), ("clash", "М1 член клэша")):
        путь = таблица_докинга(run, вариант)
        if путь is not None:
            доступные[имя] = прочитать(путь)
    if len(доступные) < 2:
        return

    общие = sorted(set.intersection(*(set(т) for т in доступные.values())))
    базовое = "М0 дискретный"
    print(f"\n=== докинг Vina: прямое сравнение вариантов, {len(общие)} общих молекул ===")

    # Исходная энергия обязана совпадать: это одни и те же молекулы до оптимизации.
    # Расхождение означало бы, что таблицы посчитаны на разных наборах, и сравнивать
    # их нельзя — молчаливо продолжать в этом случае значило бы печатать чушь.
    исходные = {
        имя: np.array([т[m]["vina_score_before"] for m in общие]) for имя, т in доступные.items()
    }
    if not np.allclose(*исходные.values()):
        print("  таблицы посчитаны на разных наборах молекул, сравнение невозможно")
        return

    for величина, подпись in (("vina_score", "поза как есть"), ("vina_min", "после миним.")):
        до = np.array([доступные[базовое][m][f"{величина}_before"] for m in общие])
        строка = f"  {подпись:14s} исходные {np.median(до):+7.2f}"
        значения: dict[str, np.ndarray] = {}
        for имя, т in доступные.items():
            после = np.array([т[m][f"{величина}_after"] for m in общие])
            значения[имя] = после
            строка += f" | {имя.split()[0]} {np.median(после):+7.2f}"
        print(строка)
        для_теста = значения["М1 член клэша"]
        тест = stats.wilcoxon(для_теста, значения[базовое], zero_method="zsplit")
        лучше = int((для_теста < значения[базовое]).sum())
        print(
            f"    М1 против М0: лучше у {лучше}/{len(общие)} молекул, "
            f"Уилкоксон p = {тест.pvalue:.3g}, "
            f"разница медиан {np.median(для_теста) - np.median(значения[базовое]):+.2f} ккал/моль"
        )
        # Медиана здесь обманчива, и это не оговорка, а измеренное свойство: разница
        # между вариантами резко асимметрична. В типичной молекуле её нет, а весь
        # выигрыш М1 сидит в хвосте — там, где базовый потенциал загнал позу в белок.
        # Без децилей сравнение выглядело бы как «разницы почти нет».
        разница = для_теста - значения[базовое]
        низ, верх = np.percentile(разница, [10, 90])
        print(f"    дециль разницы: 10% {низ:+.2f}, 90% {верх:+.2f} ккал/моль")

    # Положительная энергия позы означает грубое столкновение с белком: отталкивание
    # у Vina растёт неограниченно, поэтому наложение в пару десятых ангстрема уводит
    # величину далеко в плюс. Число таких поз — самый наглядный итог сравнения.
    до_оптимизации = np.array([доступные[базовое][m]["vina_score_before"] for m in общие])
    исходных = int((до_оптимизации > 0).sum())
    строка = f"  поз с положительной энергией: исходные {исходных}"
    for имя, т in доступные.items():
        плохих = int((np.array([т[m]["vina_score_after"] for m in общие]) > 0).sum())
        строка += f" | {имя.split()[0]} {плохих}"
    print(f"{строка} (из {len(общие)})")


if __name__ == "__main__":
    raise SystemExit(main())
